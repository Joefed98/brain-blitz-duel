/**
 * Builds the server-only Orbit black-hole bank (src/lib/duel/orbitHoleBank.server.ts)
 * for orbitRev 4: for each proved rev-3 bank course, three black holes found and
 * proved by scripts/orbit-hole-lib.ts (buildHoles), with the witness run's taps
 * (every hole taken, sun reached) so a check can re-verify an entry by replay.
 * Courses whose holes cannot be proved are left out and keep rev 3.
 *
 * Deterministic: the same bank always gives the same holes.
 *
 *   bun scripts/orbit-hole-bank.ts                  # build and write (8 workers)
 *   bun scripts/orbit-hole-bank.ts <from> <to> <out.json>   # one shard (worker mode)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { decodeRev3Planets, encodeOrbitHoles } from "../src/lib/arcade/orbitRev3";
import { ORBIT_REV3_BANK } from "../src/lib/duel/orbitRev3Bank.server";
import type { OrbitHoleBankEntry } from "../src/lib/duel/orbitHoleBank.server";
import { buildHoles, holeFailure } from "./orbit-hole-lib";

const OUT = "src/lib/duel/orbitHoleBank.server.ts";
const WORKERS = 8;

function buildRange(from: number, to: number): OrbitHoleBankEntry[] {
  const out: OrbitHoleBankEntry[] = [];
  for (let i = from; i < to && i < ORBIT_REV3_BANK.length; i++) {
    const entry = ORBIT_REV3_BANK[i]!;
    const witness = buildHoles(decodeRev3Planets(entry.planets), entry.taps, entry.seed);
    if (!witness) {
      console.log(`  course ${i} (seed ${entry.seed}): no holes — ${holeFailure}`);
      continue;
    }
    out.push({ seed: entry.seed, holes: encodeOrbitHoles(witness.holes), taps: witness.taps, ticks: witness.ticks });
  }
  return out;
}

if (process.argv[4]) {
  const started = Date.now();
  const out = buildRange(Number(process.argv[2]), Number(process.argv[3]));
  console.log(`shard ${process.argv[2]}-${process.argv[3]}: ${out.length} courses with holes in ${((Date.now() - started) / 1000).toFixed(1)} s`);
  writeFileSync(process.argv[4], JSON.stringify(out));
} else {
  const per = Math.ceil(ORBIT_REV3_BANK.length / WORKERS);
  const parts = Array.from({ length: WORKERS }, (_, w) => `/tmp/orbit-hole-part-${w}.json`);
  const started = Date.now();
  const procs = parts.map((file, w) =>
    Bun.spawn(["bun", "run", "scripts/orbit-hole-bank.ts", String(w * per), String((w + 1) * per), file], { stdout: "inherit", stderr: "inherit" }),
  );
  const codes = await Promise.all(procs.map((p) => p.exited));
  codes.forEach((code, i) => {
    if (code !== 0) throw new Error(`worker ${i} exited ${code}`);
  });
  const entries = parts.flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as OrbitHoleBankEntry[]);
  writeFileSync(
    OUT,
    `/* Generated by scripts/orbit-hole-bank.ts — do not edit by hand. */\nimport type { OrbitHoleRow } from "@/lib/arcade/orbitRev3";\n\nexport interface OrbitHoleBankEntry {\n  /** The rev-3 bank course (ORBIT_REV3_BANK) these holes belong to. */\n  seed: number;\n  /** Three black holes: [from, to, x, y] (see decodeOrbitHoles). */\n  holes: OrbitHoleRow[];\n  /** Witness taps: a run that takes every hole and reaches the sun. */\n  taps: number[];\n  /** The witness run's finishing tick. */\n  ticks: number;\n}\n\nexport const ORBIT_HOLE_BANK: OrbitHoleBankEntry[] = ${JSON.stringify(entries)};\n`,
  );
  console.log(`wrote ${entries.length} / ${ORBIT_REV3_BANK.length} courses with holes to ${OUT} in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}
