/**
 * Builds the banks for the Logic overhaul's slow levels (stage 3, 16 Nov 2026) into
 * src/lib/duel/logicLevelBank.server.ts: Trail Hard and Expert and Regions Expert take seconds to build live (a path whose
 * fewest unique numbers are hard enough; an 8 × 8 region map the solver proves), too slow for a room's deal, so each is
 * dealt from a bank built here, exactly as the live deal builds it (dealLogicLevel with the bank off, seeded per entry).
 * Every entry is unique and fair for a person by construction; logic-levels-check re-proves them.
 *
 *   bun scripts/logic-level-bank.ts [--part=k/n]      build (or one part, written to .logic-level-bank/part-k.json)
 *   bun scripts/logic-level-bank.ts --merge=n         join n parts into the bank file
 *   bun scripts/logic-level-bank.ts --check[=k/n]     rebuild entries (or a part) and compare with the bank, byte for byte
 *   --only=type:level[,…]                              build, merge or check only those banks (a merge keeps the others)
 */
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

import { withSeededRandom } from "../src/lib/duel/random";
import { dealLogicLevel, logicLevelBankOff } from "../src/lib/duel/logicLevelDeal.server";
import { LOGIC_LEVEL_BANKED, LOGIC_LEVEL_BANK_SIZE, logicLevelBankSeed } from "../src/lib/duel/logicLevelBankSpec";
import type { PuzzleData, PuzzleType } from "../src/lib/duel/types";
import type { Level } from "../src/lib/levels/levels";

const OUT = "src/lib/duel/logicLevelBank.server.ts";
const PARTS = ".logic-level-bank";

const arg = (name: string) => process.argv.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
const value = (name: string) => arg(name)?.split("=")[1];

const only = value("only")?.split(",");
/** Every (bank, entry) job in a fixed order (only the asked-for banks with --only). */
const jobs = LOGIC_LEVEL_BANKED.filter(({ type, level }) => !only || only.includes(`${type}:${level}`)).flatMap(({ type, level }) => Array.from({ length: LOGIC_LEVEL_BANK_SIZE }, (_, i) => ({ type, level, i })));

function build(type: PuzzleType, level: Level, i: number): PuzzleData {
  const seed = logicLevelBankSeed(type, level, i);
  return logicLevelBankOff(() => withSeededRandom(seed, () => dealLogicLevel(type, level, () => seed)))!;
}

const key = (type: string, level: string) => `${type}:${level}`;

function partOf(spec: string | undefined): { k: number; n: number } | null {
  if (!spec) return null;
  const [k, n] = spec.split("/").map(Number);
  return k && n ? { k, n } : null;
}

function render(entries: Record<string, PuzzleData[]>): string {
  const lines = Object.entries(entries).map(([k, list]) => `  ${JSON.stringify(k)}: [\n${list.map((p) => `    ${JSON.stringify(p)},`).join("\n")}\n  ],`);
  return `/* Generated by scripts/logic-level-bank.ts; do not edit by hand. */
import type { PuzzleData } from "./types";

/** The Logic overhaul's slow levels (logicLevelBankSpec.ts), "type:level" → boards, each unique and fair for a person. */
export const LOGIC_LEVEL_BANK: Record<string, PuzzleData[]> = {
${lines.join("\n")}
};
`;
}

const check = arg("check");
const merge = value("merge");
if (merge) {
  // With --only, the banks not rebuilt are kept from the bank file as it is.
  const kept = only ? (await import("../src/lib/duel/logicLevelBank.server")).LOGIC_LEVEL_BANK : {};
  const all: Record<string, PuzzleData[]> = Object.fromEntries(Object.entries(kept).filter(([k]) => !only!.includes(k)).map(([k, v]) => [k, [...v]]));
  for (let k = 1; k <= Number(merge); k++) {
    const part = JSON.parse(readFileSync(`${PARTS}/part-${k}.json`, "utf8")) as { type: string; level: string; i: number; p: PuzzleData }[];
    for (const e of part) (all[key(e.type, e.level)] ??= [])[e.i] = e.p;
  }
  for (const { type, level } of LOGIC_LEVEL_BANKED) {
    const list = all[key(type, level)] ?? [];
    if (list.length !== LOGIC_LEVEL_BANK_SIZE || list.some((p) => !p)) throw new Error(`${key(type, level)}: missing entries`);
  }
  writeFileSync(OUT, render(all));
  console.log(`wrote ${OUT}`);
} else {
  const part = partOf(typeof check === "string" ? value("check") : value("part"));
  const mine = part ? jobs.filter((_, j) => j % part.n === part.k - 1) : jobs;
  const t0 = Date.now();
  if (check) {
    const { LOGIC_LEVEL_BANK } = await import("../src/lib/duel/logicLevelBank.server");
    let bad = 0;
    for (const job of mine) {
      const stored = LOGIC_LEVEL_BANK[key(job.type, job.level)]?.[job.i];
      if (JSON.stringify(build(job.type, job.level, job.i)) !== JSON.stringify(stored)) (bad++, console.log(`FAIL ${key(job.type, job.level)} #${job.i}`));
    }
    console.log(`${mine.length - bad} of ${mine.length} entries rebuilt byte for byte (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
    process.exit(bad ? 1 : 0);
  }
  const out: { type: string; level: string; i: number; p: PuzzleData }[] = [];
  // A part keeps a journal of the entries it has built (D4, 22 Nov 2026: a machine restart lost two hours of
  // builds), one JSON line each, and on a restart takes those as built: every entry is a pure function of its seed, so
  // a journalled entry is exactly what building it again would give (--check proves the merged bank either way).
  const journal = part ? `${PARTS}/journal-${part.k}-of-${part.n}.jsonl` : null;
  const done = new Map<string, PuzzleData>();
  if (journal && existsSync(journal)) {
    for (const line of readFileSync(journal, "utf8").split("\n")) {
      if (!line.trim()) continue;
      try {
        const e = JSON.parse(line) as { type: string; level: string; i: number; p: PuzzleData };
        done.set(`${e.type}:${e.level}:${e.i}`, e.p);
      } catch {
        /* a line cut short by the restart: built again */
      }
    }
    console.log(`resuming: ${done.size} entries from ${journal}`);
  }
  if (journal && !existsSync(PARTS)) mkdirSync(PARTS);
  for (const job of mine) {
    const was = done.get(`${job.type}:${job.level}:${job.i}`);
    const p = was ?? build(job.type, job.level, job.i);
    out.push({ ...job, p });
    if (journal && !was) appendFileSync(journal, `${JSON.stringify({ ...job, p })}\n`);
    if (out.length % 10 === 0) console.log(`${out.length} of ${mine.length} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
  }
  if (part) {
    if (!existsSync(PARTS)) mkdirSync(PARTS);
    writeFileSync(`${PARTS}/part-${part.k}.json`, JSON.stringify(out));
    console.log(`wrote ${PARTS}/part-${part.k}.json`);
  } else {
    const all: Record<string, PuzzleData[]> = {};
    for (const e of out) (all[key(e.type, e.level)] ??= [])[e.i] = e.p;
    writeFileSync(OUT, render(all));
    console.log(`wrote ${OUT}`);
  }
}
