"""
The avatar renders into the app (S5 step 2, PR A).

    python scripts/identity-art/publish_avatars.py <renders dir> [--check]

Reads <renders>/<id>/<variant>.png (avatar_build.py) and writes public/identity/avatars/<id>/<variant>.webp (the paint's
mask and gloss lossless, everything else WebP quality 88) and src/design/identity/avatarArt.data.ts: every avatar's
variants with a content hash, which the app puts on each URL so a re-rendered file is fetched again. --check rebuilds
both in memory and fails if either differs from what is on disk.
"""
import hashlib
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "public/identity/avatars"
DATA = ROOT / "src/design/identity/avatarArt.data.ts"
LOSSLESS = {"tint-mask", "neon-mask"}


def encode(png, variant):
    im = Image.open(png).convert("RGBA")
    buf = io.BytesIO()
    if variant in LOSSLESS:
        im.convert("L").save(buf, "WEBP", lossless=True, method=6)
    else:
        im.save(buf, "WEBP", quality=88, method=6)
    return buf.getvalue()


def main():
    src = Path(sys.argv[1])
    check = "--check" in sys.argv
    files, table = {}, {}
    for d in sorted(p for p in src.iterdir() if p.is_dir()):
        for png in sorted(d.glob("*.png")):
            v = png.stem
            data = encode(png, v)
            files[OUT / d.name / f"{v}.webp"] = data
            table.setdefault(d.name, {})[v] = hashlib.sha256(data).hexdigest()[:10]
    lines = [
        "// Generated by scripts/identity-art/publish_avatars.py (S5 step 2): every avatar's Blender renders in",
        "// public/identity/avatars/<id>/<variant>.webp, each with its content hash (the URL's ?v=). Do not edit.",
        "export const AVATAR_ART: Record<string, Readonly<Record<string, string>>> = {",
    ]
    for aid, vs in table.items():
        body = ", ".join(f'"{k}": "{h}"' for k, h in sorted(vs.items()))
        lines.append(f'  "{aid}": {{ {body} }},')
    lines.append("};")
    total = sum(len(b) for b in files.values())
    lines.append(f"/** The files' total size in bytes ({len(files)} files). */")
    lines.append(f"export const AVATAR_ART_BYTES = {total};")
    text = "\n".join(lines) + "\n"
    if check:
        bad = [str(p) for p, b in files.items() if not p.exists() or p.read_bytes() != b]
        if DATA.read_text() != text:
            bad.append(str(DATA))
        if bad:
            print("FAIL publish_avatars --check:", len(bad), "differ, e.g.", bad[:3])
            sys.exit(1)
        print(f"PASS publish_avatars --check: {len(files)} files and the data file match")
        return
    for p, b in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(b)
    DATA.write_text(text)
    print(f"{len(files)} files, {total / 1024 / 1024:.2f} MB, {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
