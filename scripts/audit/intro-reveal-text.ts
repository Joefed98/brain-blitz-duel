/**
 * Audit text export (Nov 2026): every active game's round-intro text, its "?" How to play text and its reveal lines,
 * written to docs/audit/intro-reveal-text.md from the real modules (no hand copies). Not a check; changes nothing.
 *
 *   bun scripts/audit/intro-reveal-text.ts [--report=screenshots/audit-nov-2026-final/capture-report.json]
 *       [--out=docs/audit/intro-reveal-text-final.md]
 *
 * Sources:
 *   - intro: GOAL = instructions.goal, HOW = the instruction lines without `helpOnly`, SCORE = INTRO_SCORE[type]
 *     (src/components/duel/PuzzleInstructions.tsx, not overlay), the definition's `introLine` (src/puzzles/<id>.tsx,
 *     with the intro example) and "You have N seconds" (src/components/duel/RoundIntro.tsx);
 *   - help ("?"): GOAL, every HOW line, SCORE = instructions.score (PuzzleInstructions overlay);
 *   - reveal: puzzles — the verdict line, `revealHeading`, the stored score parts (AnswerReveal.tsx); arcade — the
 *     standard's part labels and maximums (src/lib/arcade/standard/index.ts, else scripts/arcade-standard/<id>.ts),
 *     the line format (stdLines) and the one-line summary (revealSummary, ArcadeReveal.tsx); and, for every game, the
 *     reveal text actually shown after the audit's practice run (scripts/audit/audit-capture.ts's report).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { ARCADE_GROUPS } from "../../src/lib/duel/arcadeGroups";
import { gameDisplayName } from "../../src/lib/duel/gameNames";
import { INTRO_SCORE } from "../../src/lib/duel/introScore";
import { ACTIVE_PUZZLE_TYPES, puzzleDef, typeTimeLimitMs, usesArcadeClock } from "../../src/lib/duel/registry";
import type { PuzzleType } from "../../src/lib/duel/types";
import { ARCADE_STANDARD } from "../../src/lib/arcade/standard";
import { exampleFor } from "../shots/examples";
import { scoreSentences } from "../../src/lib/duel/scoreList";

const args = process.argv.slice(2);
const opt = (name: string) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const REPORT = opt("report") ?? "screenshots/audit-nov-2026-final/capture-report.json";
const OUT = opt("out") ?? "docs/audit/intro-reveal-text-final.md";
const SHOTS = dirname(REPORT);

const report: Record<string, { revealText?: string[]; reveal?: string; score?: string | null; error?: string }> =
  existsSync(REPORT) ? JSON.parse(readFileSync(REPORT, "utf8")) : {};

/** The standard entries in scripts/arcade-standard/ (their `parts` labels; nothing there is run). */
const entries: Record<string, { field: string; rev: number; parts: readonly { key: string; label: string; max: number }[] }> = {};
for (const f of readdirSync(new URL("../arcade-standard/", import.meta.url))) {
  if (!f.endsWith(".ts") || f === "entry.ts") continue;
  const mod = (await import(`../arcade-standard/${f}`)) as { entry?: (typeof entries)[string] };
  if (mod.entry) entries[f.replace(/\.ts$/, "")] = mod.entry;
}

/** Each type's definition module, from the registry's own imports (e.g. wordhunt → src/puzzles/wordHunt.tsx). */
const REGISTRY_SRC = readFileSync(new URL("../../src/lib/duel/registry.ts", import.meta.url), "utf8");
const defFile = (type: string): string => {
  const ident = new RegExp(`\\n\\s*${type}:\\s*(\\w+),`).exec(REGISTRY_SRC.slice(REGISTRY_SRC.indexOf("BASE_REGISTRY")))?.[1];
  const mod = ident ? new RegExp(`import \\{[^}]*\\b${ident}\\b[^}]*\\} from "@/puzzles/([^"]+)"`).exec(REGISTRY_SRC)?.[1] : undefined;
  if (!mod) return `src/puzzles/ (definition of ${type})`;
  return existsSync(`src/puzzles/${mod}.tsx`) ? `src/puzzles/${mod}.tsx` : `src/puzzles/${mod}.ts`;
};

const CATEGORY_ORDER = ["word", "number", "speed", "attention", "pattern", "logic"] as const;
const groupOf = (t: string) => ARCADE_GROUPS.find((g) => g.games.includes(t));

const md: string[] = [];
const q = (s: string) => s.replace(/\n/g, " ");
md.push("# Intro, How to play and reveal text: every active game (final audit after the text pass, Nov 2026)");
md.push("");
md.push(
  `Generated by \`bun scripts/audit/intro-reveal-text.ts\` from the live modules (${ACTIVE_PUZZLE_TYPES.length} active games, registry order within each section). After the text pass of 4 Nov 2026 (plain score lists, no internal jargon). Screenshots: \`${SHOTS}/\`.`,
);
md.push("");
md.push("Where each text lives:");
md.push("");
md.push("- **Intro** (`src/components/duel/RoundIntro.tsx` → `PuzzleInstructions`, `src/components/duel/PuzzleInstructions.tsx`): GOAL `instructions.goal`; HOW the lines of `instructions.how` without `helpOnly` (\"**action** detail\"); SCORE `INTRO_SCORE[type]` (`src/lib/duel/introScore.ts`, `{max}` filled from `roundMax.ts`); then the definition's `introLine` (`src/puzzles/<id>.tsx`) when it has one, and \"You have N seconds\" (the limit, less 3 s on an arcade clock).");
md.push("- **How to play** (the \"?\" help, `PuzzleInstructions` with `overlay`): GOAL; every HOW line, `helpOnly` included; SCORE `instructions.score` (`src/lib/duel/instructions.ts`, `PUZZLE_INSTRUCTIONS`), drawn one row a sentence: one line a part (\"Part: how you earn it, up to N.\"), then penalties, then \"Total 200.\" (`scoreList`, src/lib/duel/scoreList.ts).");
md.push("- **Puzzle reveal** (`src/components/duel/AnswerReveal.tsx`): the verdict line `verdictLine()` — \"Solved in N.N s\" / \"Solved\" / \"Partly solved\" / \"Not solved\" (\"Scoring…\" while grading); under it `revealHeading` (default \"The answer was\"); the stored score; a near-miss line (`src/lib/duel/nearMiss.ts`, some games); then the definition's `Reveal` component (`src/puzzles/<id>.tsx`) with the stored score parts (`scorePartsText`, `src/lib/duel/puzzleScoreRev.ts`: \"150 + 11 moves + 15 speed\", \"N for progress\").");
md.push("- **Arcade reveal** (`src/components/duel/ArcadeReveal.tsx`, lines built on the server by `buildArcadeReveal` in `src/lib/arcade/reveal.ts`): on the arcade scoring standard one line per part, `\"<label>: <detail> → <points> of <max>\"`, then `\"Total → N of 200\"` (or `\"At least 1 for playing → 1\"`; `stdLines`, `src/lib/arcade/arcadeStandard.ts`), shown in plain words (`breakdownRows`, src/lib/duel/revealBreakdown.ts) and folded in rooms to one line until tapped: `\"N points · <first part> X + bonuses Y\"` (`revealSummary`); plus stat tiles and the score chart.");
md.push(`- **Shown after the audit run**: the reveal's visible text after the practice run that made \`-reveal.png\` (a skill-band bot, a driver or scripted input; see \`${SHOTS}/capture-report.json\`). Lines are as \`innerText\` reads them, including header and button labels.`);
md.push("");

function section(type: PuzzleType) {
  const def = puzzleDef(type);
  const ins = def.instructions;
  md.push(`### ${gameDisplayName(type)} (\`${type}\`)`);
  md.push("");
  const ownLimit = (exampleFor(type) as { timeLimitMs?: number }).timeLimitMs;
  const limitMs = typeof ownLimit === "number" && ownLimit > 0 ? ownLimit : typeTimeLimitMs(type);
  const seconds = Math.round((limitMs - (usesArcadeClock(type) ? 3000 : 0)) / 1000);
  let introLine: string | null = null;
  try {
    introLine = def.introLine?.(exampleFor(type) as never) ?? null;
  } catch {
    introLine = null;
  }
  md.push("**Intro**");
  md.push("");
  md.push(`- GOAL: ${q(ins.goal)}`);
  for (const l of ins.how.filter((l) => !l.helpOnly)) md.push(`- HOW: **${q(l.action)}** ${q(l.detail)}`);
  md.push(`- SCORE: ${q(INTRO_SCORE[type])}`);
  if (introLine) md.push(`- Intro line (\`introLine\` in ${defFile(type)}, intro example): ${q(introLine)}`);
  md.push(`- Time line: You have ${seconds} seconds`);
  md.push("");
  md.push("**How to play (\"?\")**");
  md.push("");
  md.push(`- GOAL: ${q(ins.goal)}`);
  for (const l of ins.how) md.push(`- HOW${l.helpOnly ? " (help only)" : ""}: **${q(l.action)}** ${q(l.detail)}`);
  md.push("- SCORE (one row a part):");
  for (const row of scoreSentences(ins.score)) md.push(`  - ${q(row)}`);
  md.push("");
  md.push("**Reveal**");
  md.push("");
  if (def.category === "arcade" || (def as { arcadeRun?: unknown }).arcadeRun) {
    const spec = ARCADE_STANDARD[type]?.spec ?? null;
    const entry = entries[type];
    const parts = spec?.parts ?? entry?.parts ?? null;
    if (parts) {
      const src = spec ? `\`${spec.field} ${spec.rev}\` spec, src/lib/arcade/standard/` : `\`${entry!.field} ${entry!.rev}\`, scripts/arcade-standard/${type}.ts (check entry labels)`;
      md.push(`- Standard parts (${src}): ${parts.map((p) => `${q(p.label)} (max ${p.max})`).join("; ")}`);
      md.push(`- Lines: stored as \`<part>: <detail> → <points> of <max>\` per part, then \`Total → N of 200\`; shown as \`<part>: <detail>: <points> of <max> points\`; folded: \`N points · <first part> X + bonuses Y\``);
    } else md.push("- Not on the arcade scoring standard: lines from `buildArcadeReveal` (src/lib/arcade/reveal.ts) for this game.");
  } else {
    md.push(`- Verdict: Solved in N.N s / Partly solved / Not solved; heading: ${q(def.revealHeading ?? "The answer was")}`);
    md.push(`- Board and lines: \`Reveal\` of the definition in ${defFile(type)}, score parts as \`scorePartsText\``);
  }
  const r = report[type];
  if (r?.revealText?.length) {
    md.push(`- Shown after the audit run (${r.reveal ?? "?"}, score ${r.score ?? "?"}):`);
    md.push("");
    md.push("  ```text");
    for (const line of r.revealText.slice(0, 40)) md.push(`  ${line}`);
    md.push("  ```");
  } else if (r?.error) md.push(`- Audit run: no reveal captured (${r.error}).`);
  md.push("");
}

for (const cat of CATEGORY_ORDER) {
  const games = ACTIVE_PUZZLE_TYPES.filter((t) => puzzleDef(t).category === cat);
  md.push(`## ${cat[0]!.toUpperCase()}${cat.slice(1)} (${games.length})`);
  md.push("");
  for (const t of games) section(t);
}
for (const g of ARCADE_GROUPS) {
  const games = ACTIVE_PUZZLE_TYPES.filter((t) => puzzleDef(t).category === "arcade" && groupOf(t)?.id === g.id);
  md.push(`## Arcade · ${g.label} (${games.length})`);
  md.push("");
  for (const t of games) section(t);
}
const loose = ACTIVE_PUZZLE_TYPES.filter((t) => puzzleDef(t).category === "arcade" && !groupOf(t));
if (loose.length) {
  md.push(`## Arcade · no group (${loose.length})`);
  md.push("");
  for (const t of loose) section(t);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md.join("\n") + "\n");
console.log(`${OUT}: ${ACTIVE_PUZZLE_TYPES.length} games`);
