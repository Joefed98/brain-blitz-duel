/**
 * Builds the Bomb Defusal banks.
 *
 *   bun scripts/bomb-bank.ts --v3 [300]      # version 3 (new rounds): src/lib/duel/bombBankV3.server.ts
 *   bun scripts/bomb-bank.ts --v3 --check    # rebuild version 3 in memory and compare byte for byte
 *   bun scripts/bomb-bank.ts 300            # version 2 (kept for its proof): src/lib/duel/bombBank.server.ts
 *   bun scripts/bomb-bank.ts 75 /tmp/a.json # one version-2 shard (merge with --merge)
 *   bun scripts/bomb-bank.ts --merge /tmp/a.json /tmp/b.json ...
 *
 * Version 3 (14 Oct 2026): each card comes from generatePlainBombPanel() under
 * a fixed seed per entry (entry i uses seed BOMB_V3_SEED + i), so the bank
 * rebuilds exactly: a random six-action plan, plain clues true of it narrowed
 * until only the plan survives all 60,480 ordered six-action sequences, then
 * pruned so every clue is needed (6–9 clues). scripts/bomb-v3-check.ts proves
 * every card again from its clue text alone.
 *
 * Version 2: generateBombPanel(2), unseeded; no longer drawn by rooms.
 */
import { readFileSync, writeFileSync } from "node:fs";

import { generateBombPanel, generatePlainBombPanel } from "../src/lib/duel/bomb.server";
import { withSeededRandom } from "../src/lib/duel/random";
import type { BombPuzzleData } from "../src/lib/duel/types";

const OUT = "src/lib/duel/bombBank.server.ts";
const OUT_V3 = "src/lib/duel/bombBankV3.server.ts";
export const BOMB_V3_SEED = 140_000;

function write(entries: BombPuzzleData[]) {
  const unique = new Map(entries.map((entry) => [JSON.stringify(entry), entry]));
  writeFileSync(
    OUT,
    `/* Generated by scripts/bomb-bank.ts — do not edit by hand. */\nimport type { BombPuzzleData } from "./types";\n\nexport const BOMB_V2_BANK: BombPuzzleData[] = ${JSON.stringify([...unique.values()])};\n`,
  );
  console.log(`wrote ${unique.size} panels to ${OUT}`);
}

export function buildV3(count: number): string {
  const out: BombPuzzleData[] = [];
  for (let i = 0; i < count; i++) out.push(withSeededRandom(BOMB_V3_SEED + i, () => generatePlainBombPanel().puzzle));
  const lines = out.map((entry) => `  ${JSON.stringify(entry)},`).join("\n");
  return `/* Generated by scripts/bomb-bank.ts --v3 — do not edit by hand. Entry i is generatePlainBombPanel() under seed ${BOMB_V3_SEED} + i. */\nimport type { BombPuzzleData } from "./types";\n\nexport const BOMB_V3_BANK: BombPuzzleData[] = [\n${lines}\n];\n`;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.includes("--v3")) {
    const count = Number(args.find((a) => /^\d+$/.test(a)) ?? 300);
    const started = Date.now();
    const text = buildV3(count);
    if (args.includes("--check")) {
      const same = readFileSync(OUT_V3, "utf8") === text;
      console.log(same ? `${OUT_V3}: rebuilds byte for byte (${count} cards)` : `FAIL: ${OUT_V3} differs from a rebuild`);
      if (!same) process.exit(1);
    } else {
      writeFileSync(OUT_V3, text);
      console.log(`wrote ${count} cards to ${OUT_V3} in ${((Date.now() - started) / 1000).toFixed(0)} s`);
    }
  } else if (args[0] === "--merge") {
    write(args.slice(1).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as BombPuzzleData[]));
  } else {
    const count = Number(args[0] ?? 300);
    const out: BombPuzzleData[] = [];
    const started = Date.now();
    for (let i = 0; i < count; i++) out.push(generateBombPanel(2).puzzle);
    console.log(`built ${count} panels in ${((Date.now() - started) / 1000).toFixed(0)} s`);
    if (args[1]) writeFileSync(args[1], JSON.stringify(out));
    else write(out);
  }
}
