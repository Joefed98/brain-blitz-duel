import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Window } from 'happy-dom';
import { devDisplayAllowed, setDevDisplayKey } from '../src/lib/devDisplay';
const window = new Window({ url: 'http://localhost:8080/practice?dev=1&key=test-key' });
Object.defineProperty(globalThis, 'window', { configurable: true, value: window });
Object.defineProperty(globalThis, 'Event', { configurable: true, value: window.Event });
assert.equal(devDisplayAllowed(), false, 'dev=1 and an unchecked key cannot show diagnostics');
setDevDisplayKey('test-key');
assert.equal(devDisplayAllowed(), true);
window.history.replaceState(null, '', '?dev=1&key=other');
assert.equal(devDisplayAllowed(), false);
window.history.replaceState(null, '', '?key=test-key');
assert.equal(devDisplayAllowed(), false);
setDevDisplayKey(null);
const layer = readFileSync('src/components/duel/FxLayer.tsx', 'utf8');
assert.match(layer, /if \(event\.primitive === "glow" \|\| event\.primitive === "shake"\) return/);
assert.doesNotMatch(layer, /fx-outline/);
const css = readFileSync('src/styles.css', 'utf8');
assert.doesNotMatch(css, /\.fx-outline/);
assert.match(css, /\.game-screen :focus:not\(:focus-visible\)/);
const practice = readFileSync('src/routes/practice.tsx', 'utf8');
assert.match(practice, /!exampleRun\.current \|\| !demoKey/);
assert.match(readFileSync('src/components/duel/IntroDemo.tsx', 'utf8'), /DEMO_SHOW_TOUCHES = false/);
console.log('PASS shared-box suppression, keyboard-only focus, recorder gates and accepted-key-only diagnostic visibility. No browser tests.');