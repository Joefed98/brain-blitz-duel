/**
 * The Shop pages' art (the Shop pages session, 14 Nov 2026): the style guide's 3D art-kit coin, Plus and Joules
 * renders (docs/design/style-guide/art/*.png, 192 px) cut to the sizes the Shop, Pass and Plus draw them, at 1x, 2x and,
 * where the source allows, 3x, as WebP in public/shop-art/, plus src/components/shop/shopKitArt.data.ts (each image's
 * url with its content hash, its size and the alt text). Never upscaled. The same method as scripts/nav-art.ts.
 *
 *   bun scripts/shop-art.ts          rebuild
 *   bun scripts/shop-art.ts --check  rebuild in memory and fail if anything on disk differs
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/shop-art");
const DATA = join(ROOT, "src/components/shop/shopKitArt.data.ts");

/** Every image the Shop pages draw: its art-kit source, the CSS px it is drawn at, and what it shows. */
export const SHOP_ART = {
  coin: { src: "coins", px: 44, alt: "A Joulz coin" },
  plus: { src: "plus", px: 56, alt: "Joulz Plus" },
  joules: { src: "joules", px: 40, alt: "Joules" },
} as const;

async function build(): Promise<{ files: Map<string, Buffer>; data: string }> {
  const files = new Map<string, Buffer>();
  const entries: string[] = [];
  for (const [name, spec] of Object.entries(SHOP_ART)) {
    const image = await loadImage(readFileSync(join(SOURCE, `${spec.src}.png`)));
    const urls: string[] = [];
    for (const scale of [1, 2, 3]) {
      const size = spec.px * scale;
      if (size > image.width) continue;
      const canvas = createCanvas(size, size);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, size, size);
      const bytes = Buffer.from(await canvas.encode("webp", 88));
      const file = `${name}-${scale}x.webp`;
      files.set(file, bytes);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      urls.push(`"/shop-art/${file}?v=${hash}"`);
    }
    entries.push(`  ${name}: { px: ${spec.px}, alt: ${JSON.stringify(spec.alt)}, urls: [${urls.join(", ")}] },`);
  }
  const data = `// Generated by scripts/shop-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x, 2x and (where the 192 px source allows) 3x WebP.\nexport const SHOP_KIT_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type ShopKitArtName = keyof typeof SHOP_KIT_ART;\n`;
  return { files, data };
}

const check = process.argv.includes("--check");
const { files, data } = await build();
let total = 0;
for (const b of files.values()) total += b.length;
if (check) {
  const problems: string[] = [];
  for (const [file, bytes] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) problems.push(`public/shop-art/${file} differs`);
  }
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("shopKitArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/shop-art.ts)`);
    process.exit(1);
  }
  console.log(`shop art matches: ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
}
