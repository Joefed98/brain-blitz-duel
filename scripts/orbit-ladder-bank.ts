/**
 * Builds Orbit's orbitRev 17 banks (D5, 23 Nov 2026; docs/arcade-standard/orbit.md "orbitRev 17: lines, belts and
 * levels"): for each bank seed of a level (LADDER_BANK_SEED, fixed integers), a course built and proved by
 * scripts/orbit-ladder-lib.ts (buildLadderCourse: the level's belts, black holes and features, and a witness held to the
 * human limits that reaches the sun with every feature). Seeds whose salts all fail are left out. Server-only output:
 * src/lib/duel/orbitLadderBank.server.ts (Normal) and orbitLadderBank<Level>.server.ts. orbitRev 14–16's banks
 * (scripts/orbit-fuel-bank.ts) are untouched: the era pin orbitPreLost still deals them.
 *
 * Deterministic: the same seeds always give the same bank, byte for byte.
 *
 *   bun scripts/orbit-ladder-bank.ts --level=normal|easy|hard|expert [count] [--dir=<cache>] [--workers=1]   build (or resume) and write
 *   bun scripts/orbit-ladder-bank.ts --level=… --merge [count] [--dir=…]   write the longest prefix of bank seeds the cache holds
 *   bun scripts/orbit-ladder-bank.ts --level=… --check [n]                 rebuild the first n entries (default 1) and compare, no write
 *   bun scripts/orbit-ladder-bank.ts --level=… --prove                     every entry's witness through the server on orbitRev 17 at the
 *                                                                          level: 200 on the level's lines, the human limits kept
 *   bun scripts/orbit-ladder-bank.ts --worker <w> <n> <count> <dir> --level=…   one worker (bank seeds k ≡ w mod n)
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { decodeOrbitExtras, decodeOrbitHoles, decodeRev3Planets, encodeOrbitExtras, encodeOrbitHoles, encodeRev3Planets, orbitXpCounts, ORBIT_REV3_WORLD_W, type OrbitLevelName } from "../src/lib/arcade/orbitRev3";
import type { OrbitLadderBankEntry } from "../src/lib/duel/orbitLadderBank.server";
import { buildLadderCourse, ladderFailure, ladderPuzzle, ladderServerScore, ladderStart, ladderWitnessRun } from "./orbit-ladder-lib";

export type LadderLevel = "normal" | OrbitLevelName;
export const LADDER_LEVELS: readonly LadderLevel[] = ["normal", "easy", "hard", "expert"];
/** Seeds tried for each level's bank (the bank is the ones that built). */
export const LADDER_BANK_COUNT: Readonly<Record<LadderLevel, number>> = { normal: 16, easy: 12, hard: 12, expert: 12 };
const LADDER_SALT: Readonly<Record<LadderLevel, number>> = { normal: 0x51ed270b, easy: 0x2a9f3c1d, hard: 0x6b43a9b5, expert: 0x19e3779b };
/** The k-th bank seed of a level's orbitRev 17 bank (fixed integers, distinct from orbitRev 14–16's). */
export const LADDER_BANK_SEED = (level: LadderLevel, k: number) => (Math.imul(k + 1, 0x2545f491) ^ LADDER_SALT[level]) | 0;
/** Salted retries a bank seed gets before it is left out. */
export const LADDER_SALTS = 8;
export const ladderBankFile = (level: LadderLevel) => `src/lib/duel/orbitLadderBank${level === "normal" ? "" : level[0]!.toUpperCase() + level.slice(1)}.server.ts`;
export const ladderBankExport = (level: LadderLevel) => (level === "normal" ? "ORBIT_LADDER_BANK" : `ORBIT_LADDER_BANK_${level.toUpperCase()}`);
const asLevel = (level: LadderLevel): OrbitLevelName | null => (level === "normal" ? null : level);

export function buildEntry(level: LadderLevel, k: number): OrbitLadderBankEntry | null {
  const seed = LADDER_BANK_SEED(level, k);
  const c = buildLadderCourse(asLevel(level), seed, LADDER_SALTS);
  if (!c) {
    console.log(`  ${level} seed ${k} (${seed}): no course — ${ladderFailure.slice(0, 400)}`);
    return null;
  }
  return { seed, build: c.build, planets: encodeRev3Planets(c.planets), holes: encodeOrbitHoles(c.holes), extras: encodeOrbitExtras(c.extras), taps: c.taps, ticks: c.ticks, perfect: c.perfect, left: c.left };
}

function source(level: LadderLevel, entries: OrbitLadderBankEntry[]): string {
  const head = `/* Generated by scripts/orbit-ladder-bank.ts --level=${level} — do not edit by hand. */\n`;
  if (level !== "normal") {
    return `${head}import type { OrbitLadderBankEntry } from "./orbitLadderBank.server";

/** Orbit's orbitRev 17 ${level} bank (docs/arcade-standard/orbit.md "orbitRev 17: lines, belts and levels"): every witness keeps the human limits and reaches the sun with every feature. */
export const ${ladderBankExport(level)}: OrbitLadderBankEntry[] = ${JSON.stringify(entries)};
`;
  }
  return `${head}import type { OrbitFuelBankEntry } from "./orbitFuelBank.server";

/** An orbitRev 17 bank course: an orbitRev 14 fuel-bank entry's fields, the witness held to the human limits, and its pace and perfect orbits. */
export interface OrbitLadderBankEntry extends OrbitFuelBankEntry {
  /** The witness's perfect orbits and ticks left at the sun (a level's lines are never above its bank's least). */
  perfect: number;
  left: number;
}

/** Orbit's orbitRev 17 Normal bank (docs/arcade-standard/orbit.md "orbitRev 17: lines, belts and levels"): every witness keeps the human limits and reaches the sun with every feature, Normal's pace and perfect orbits. */
export const ORBIT_LADDER_BANK: OrbitLadderBankEntry[] = ${JSON.stringify(entries)};
`;
}

async function loadBank(level: LadderLevel): Promise<OrbitLadderBankEntry[]> {
  const mod = (await import(`../${ladderBankFile(level)}`)) as Record<string, OrbitLadderBankEntry[]>;
  return mod[ladderBankExport(level)]!;
}

/** Every entry's witness on orbitRev 17 at the level through the server's grade: its score, the limits, the features. */
export function proveEntry(level: LadderLevel, e: OrbitLadderBankEntry): { score: number; human: boolean; why: string; all: boolean; flagged: boolean } {
  const lv = asLevel(level);
  const planets = decodeRev3Planets(e.planets), holes = decodeOrbitHoles(e.holes), extras = decodeOrbitExtras(e.extras);
  const w = ladderWitnessRun(lv, planets, holes, extras, e.taps);
  const c = orbitXpCounts(w.state);
  const g = ladderServerScore(ladderPuzzle(lv, e.seed, planets, holes, extras), () => ladderStart(lv)(planets, ORBIT_REV3_WORLD_W, holes, extras), e.taps);
  return { score: g.score, human: w.human, why: w.why, all: c.dust === c.dustTotal && c.slings === c.slingsTotal && c.threads === c.threadsTotal && w.state.finished === 1, flagged: g.flagged };
}

type CacheRow = OrbitLadderBankEntry | { seed: number; failed: true };
function readCache(dir: string): Map<number, CacheRow> {
  const out = new Map<number, CacheRow>();
  for (const f of readdirSync(dir)) {
    if (!/^orbit-ladder-w\d+-\d+\.json$/.test(f)) continue;
    for (const row of JSON.parse(readFileSync(`${dir}/${f}`, "utf8")) as CacheRow[]) out.set(row.seed, row);
  }
  return out;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const level = (args.find((a) => a.startsWith("--level="))?.slice(8) ?? "normal") as LadderLevel;
  if (!LADDER_LEVELS.includes(level)) throw new Error(`--level must be one of ${LADDER_LEVELS.join(", ")}`);
  const nums = args.filter((a) => /^\d+$/.test(a));
  if (args.includes("--prove")) {
    const bank = await loadBank(level);
    let good = 0;
    for (const e of bank) {
      const r = proveEntry(level, e);
      const ok = r.score === 200 && r.human && r.all && !r.flagged;
      if (ok) good++;
      else console.log(`FAIL ${level} bank seed ${e.seed}: ${r.score}${r.flagged ? " (flagged)" : ""}${r.human ? "" : `, ${r.why}`}${r.all ? "" : ", not every feature"}`);
    }
    console.log(good === bank.length ? `PASS: all ${good} ${level} bank courses' human-limited witnesses score 200 on orbitRev 17` : `FAIL: ${good} / ${bank.length} (${level})`);
    process.exit(good === bank.length ? 0 : 1);
  } else if (args.includes("--check")) {
    const n = Number(nums[0] ?? 1);
    const bank = await loadBank(level);
    let bad = 0;
    for (const want of bank.slice(0, n)) {
      let k = 0;
      while (LADDER_BANK_SEED(level, k) !== want.seed && k < 100000) k++;
      const got = buildEntry(level, k);
      const same = JSON.stringify(got) === JSON.stringify(want);
      if (!same) bad++;
      console.log(`${same ? "ok  " : "DIFF"} ${level} bank seed ${want.seed}`);
    }
    console.log(bad ? `FAIL: ${bad} of ${Math.min(n, bank.length)} entries differ` : `PASS: ${Math.min(n, bank.length)} entries rebuild byte for byte`);
    process.exit(bad ? 1 : 0);
  } else if (args[0] === "--worker") {
    const [w, n, count, dir] = [Number(args[1]), Number(args[2]), Number(args[3]), args[4]!];
    const done = readCache(dir);
    const file = `${dir}/orbit-ladder-w${w}-${Date.now()}.json`;
    const out: CacheRow[] = [];
    const started = Date.now();
    for (let k = w; k < count; k += n) {
      if (done.has(LADDER_BANK_SEED(level, k))) continue;
      const t0 = Date.now();
      const e = buildEntry(level, k);
      out.push(e ?? { seed: LADDER_BANK_SEED(level, k), failed: true });
      writeFileSync(file, JSON.stringify(out));
      console.log(`  ${level} seed ${k}: ${e ? `built, perfect ${e.perfect}, ${e.left} ticks left` : "failed"} in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    }
    console.log(`worker ${w}: ${out.length} seeds in ${((Date.now() - started) / 1000).toFixed(0)} s`);
  } else {
    const merge = args.includes("--merge");
    const dir = args.find((a) => a.startsWith("--dir="))?.slice(6) ?? `${process.env.TMPDIR ?? "/tmp"}/orbit-ladder-cache-${level}`;
    const workers = Number(args.find((a) => a.startsWith("--workers="))?.slice(10) ?? 1);
    mkdirSync(dir, { recursive: true });
    let count = Number(nums[0] ?? LADDER_BANK_COUNT[level]);
    const started = Date.now();
    if (!merge) {
      const procs = Array.from({ length: workers }, (_, w) => Bun.spawn(["bun", "run", "scripts/orbit-ladder-bank.ts", "--worker", String(w), String(workers), String(count), dir, `--level=${level}`], { stdout: "inherit", stderr: "inherit" }));
      const codes = await Promise.all(procs.map((p) => p.exited));
      codes.forEach((code, i) => {
        if (code !== 0) throw new Error(`worker ${i} exited ${code}`);
      });
    }
    const cache = readCache(dir);
    let k = 0;
    while (k < count && cache.has(LADDER_BANK_SEED(level, k))) k++;
    if (k < count && !merge) throw new Error(`bank seed ${k} missing from the cache`);
    count = k;
    const entries: OrbitLadderBankEntry[] = [];
    for (let i = 0; i < count; i++) {
      const row = cache.get(LADDER_BANK_SEED(level, i))!;
      if (!("failed" in row)) entries.push(row);
    }
    writeFileSync(ladderBankFile(level), source(level, entries));
    console.log(`wrote ${entries.length} / ${count} ${level} bank seeds to ${ladderBankFile(level)} in ${((Date.now() - started) / 1000).toFixed(0)} s`);
  }
}
