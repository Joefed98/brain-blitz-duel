/**
 * The first-time intro's art (the Settings, account and onboarding session, 14 Nov 2026): three of the style guide's
 * 3D art-kit renders (docs/design/style-guide/art/*.png, 192 px) cut to the intro's 128 px at 1x and 1.5x (the source's
 * full 192 px; never upscaled) as WebP in public/settings-art/, plus src/components/settings/settingsArt.data.ts (each
 * image's urls with their content hash).
 *
 *   bun scripts/settings-art.ts          rebuild
 *   bun scripts/settings-art.ts --check  rebuild in memory and fail if anything on disk differs
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/settings-art");
const DATA = join(ROOT, "src/components/settings/settingsArt.data.ts");
const PX = 128;

/** The intro's three panels: quick games (the joystick), rooms (two players), the win (the trophy). */
const ART = { games: "games", rooms: "rooms", trophy: "trophy" } as const;

const files = new Map<string, Buffer>();
const entries: string[] = [];
for (const [name, src] of Object.entries(ART)) {
  const image = await loadImage(readFileSync(join(SOURCE, `${src}.png`)));
  const urls: string[] = [];
  for (const [tag, size] of [["1x", PX], ["2x", Math.min(image.width, PX * 2)]] as const) {
    const canvas = createCanvas(size, size);
    const ctx = canvas.getContext("2d");
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = "high";
    ctx.drawImage(image, 0, 0, size, size);
    const bytes = Buffer.from(await canvas.encode("webp", 88));
    const file = `${name}-${tag}.webp`;
    files.set(file, bytes);
    urls.push(`"/settings-art/${file}?v=${createHash("sha256").update(bytes).digest("hex").slice(0, 10)}"`);
  }
  entries.push(`  ${name}: [${urls.join(", ")}],`);
}
const data = `// Generated by scripts/settings-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x (128 px) and the 192 px source (1.5x).\nexport const SETTINGS_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type SettingsArtName = keyof typeof SETTINGS_ART;\n`;

if (process.argv.includes("--check")) {
  const problems: string[] = [];
  for (const [file, bytes] of files) if (!existsSync(join(OUT, file)) || !readFileSync(join(OUT, file)).equals(bytes)) problems.push(`public/settings-art/${file} differs`);
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("settingsArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/settings-art.ts)`);
    process.exit(1);
  }
  console.log(`settings art matches: ${files.size} files`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files`);
}
