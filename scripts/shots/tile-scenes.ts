/**
 * Regenerates the game tile images (27 Oct 2026; a build tool, not a check): every scene in
 * scripts/shots/tile-scenes/ (each game's own art, a hand-made state, scene.ts has the rules) is
 * drawn in headless Chromium over the app's CSS at device pixel ratio 2, photographed, encoded as
 * WebP and written to public/tiles/<type>.webp, and src/components/app/gameIcons/tileScenes.data.ts
 * is rewritten (type → content hash, which GameIcon puts on the URL so a new picture is never
 * served from a stale cache). The same scenes give the same files every build.
 *
 *   bun scripts/shots/tile-scenes.ts [types…] [--preview=<dir>] [--cache=<name>]
 *
 * No types: every scene; listed types: only those (the others' files are kept). --preview writes
 * <dir>/preview.png: each image at 208 px (as exported), then at 64 and 34 px on its category-colour
 * tile (an arcade game's group colour), for judging. Each scene is drawn over its game's
 * background (tile-scenes/backgrounds.ts), in the same image. --cache gives this run its own Vite cache (for runs in parallel).
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { createCanvas, loadImage } from "@napi-rs/canvas";
import { chromium } from "playwright";

import { startSafeAreaServer } from "./../safe-area-server";
import { CHROMIUM_PATHS, THEME_SCREENS, VIEWPORTS, openThemeScreen } from "./../theme-screens";

const OUT_DIR = "public/tiles";
const DATA = "src/components/app/gameIcons/tileScenes.data.ts";
/** WebP quality: the first that keeps the file at or under MAX_BYTES (5–15 KB is the aim). */
const QUALITIES = [86, 80, 74, 68, 60];
const MAX_BYTES = 15_000;

const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const PREVIEW = process.argv.find((a) => a.startsWith("--preview="))?.slice(10) ?? null;
const CACHE = process.argv.find((a) => a.startsWith("--cache="))?.slice(8) ?? "";
const CATEGORY_HEX: Record<string, string> = {
  word: "#4D8CFF",
  number: "#3DDC84",
  speed: "#FF8A3D",
  attention: "#FF6BD6",
  pattern: "#B26BFF",
  logic: "#2ED3B7",
  arcade: "#FF4D4D",
};
const CHROMIUM = CHROMIUM_PATHS.find((path): path is string => Boolean(path && existsSync(path)));
mkdirSync(OUT_DIR, { recursive: true });

const server = await startSafeAreaServer({ cacheDir: `node_modules/.vite-tile-scenes${CACHE ? `-${CACHE}` : ""}`, buildId: "tile-scenes" });
const browser = await chromium.launch({ executablePath: CHROMIUM });
const written: Record<string, number> = {};
const errors: string[] = [];
try {
  const practice = THEME_SCREENS.find((s) => s.name === "practice list")!;
  const viewport = { ...VIEWPORTS[0]!, scale: 2 };
  const { context, page } = await openThemeScreen(browser, server.origin, practice, viewport);
  page.on("pageerror", (e) => errors.push(String(e)));
  page.on("console", (m) => {
    if (m.type() === "error") errors.push(m.text());
  });
  try {
    // Reduced motion pins every renderer clock at 0 (retroClock and friends), so a scene is the same picture every build.
    await page.emulateMedia({ reducedMotion: "reduce" });
    const types = await page.evaluate(async (wanted) => {
      const mod = await import(/* @vite-ignore */ "/scripts/shots/tile-scenes/harness.tsx");
      return (mod as { mountScenes: (t: string[]) => Promise<string[]> }).mountScenes(wanted);
    }, only);
    for (const type of types) {
      const png = await page.locator(`[data-tile-scene="${type}"]`).screenshot({ animations: "disabled" });
      const img = await loadImage(png);
      const canvas = createCanvas(img.width, img.height);
      canvas.getContext("2d").drawImage(img, 0, 0);
      let webp: Buffer | null = null;
      for (const q of QUALITIES) {
        webp = await canvas.encode("webp", q);
        if (webp.length <= MAX_BYTES) break;
      }
      writeFileSync(join(OUT_DIR, `${type}.webp`), webp!);
      written[type] = webp!.length;
    }
  } finally {
    await context.close();
  }
} finally {
  await browser.close();
  await server.close();
}

// The data file lists every image on disk (a partial run keeps the others).
const entries = readdirSync(OUT_DIR)
  .filter((f) => f.endsWith(".webp"))
  .sort()
  .map((f) => {
    const hash = createHash("sha256").update(readFileSync(join(OUT_DIR, f))).digest("hex").slice(0, 10);
    return `  ${f.replace(/\.webp$/, "")}: "${hash}",`;
  });
writeFileSync(
  DATA,
  `/**
 * Generated by \`bun scripts/shots/tile-scenes.ts\`; do not edit. Each game with a tile scene image
 * (public/tiles/<type>.webp) and the image's content hash, put on its URL by GameIcon.
 */
import type { PuzzleType } from "@/lib/duel/types";

export const TILE_SCENES: Partial<Record<PuzzleType, string>> = {
${entries.join("\n")}
};
`,
);
if (PREVIEW && Object.keys(written).length) {
  const { PUZZLE_REGISTRY } = await import("../../src/lib/duel/registry");
  const { arcadeGroupInfo, arcadeGroupOf } = await import("../../src/lib/duel/arcadeGroups");
  mkdirSync(PREVIEW, { recursive: true });
  const types = Object.keys(written);
  const rowH = 208 + 24;
  const sheet = createCanvas(208 + 16 + 64 + 16 + 34 + 24, types.length * rowH);
  const g = sheet.getContext("2d");
  g.fillStyle = "#1a1a1f";
  g.fillRect(0, 0, sheet.width, sheet.height);
  for (const [i, type] of types.entries()) {
    const img = await loadImage(readFileSync(join(OUT_DIR, `${type}.webp`)));
    const y = i * rowH + 12;
    g.drawImage(img, 0, y, 208, 208);
    const group = arcadeGroupOf(type);
    const colour = group ? arcadeGroupInfo(group).colour : (CATEGORY_HEX[PUZZLE_REGISTRY[type as keyof typeof PUZZLE_REGISTRY]?.category ?? "arcade"] ?? "#fff");
    for (const [x, size] of [[224, 64], [304, 34]] as const) {
      const b = Math.max(1.5, Math.round(size * 0.045 * 2) / 2);
      g.save();
      g.beginPath();
      g.roundRect(x, y, size, size, size * 0.28);
      g.clip();
      g.fillStyle = "#000";
      g.fillRect(x, y, size, size);
      g.drawImage(img, x + b, y + b, size - 2 * b, size - 2 * b);
      g.restore();
      g.beginPath();
      g.roundRect(x + b / 2, y + b / 2, size - b, size - b, size * 0.28 - b / 2);
      g.strokeStyle = colour;
      g.lineWidth = b;
      g.stroke();
    }
    g.fillStyle = "#ccc";
    g.font = "12px sans-serif";
    g.fillText(type, 224, y + 90);
  }
  writeFileSync(join(PREVIEW, "preview.png"), await sheet.encode("png"));
  console.log(`preview: ${join(PREVIEW, "preview.png")}`);
}
for (const [type, bytes] of Object.entries(written)) console.log(`${type.padEnd(12)} ${(bytes / 1024).toFixed(1)} KB`);
if (errors.length) {
  console.log(`FAIL: page errors while drawing:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}
console.log(`wrote ${Object.keys(written).length} tile images to ${OUT_DIR} and ${DATA}`);
process.exit(0);
