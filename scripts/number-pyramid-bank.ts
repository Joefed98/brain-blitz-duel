/** Builds 400 sets of three uniquely solvable Number Pyramid boards. */
import { writeFileSync } from "node:fs";
import { npBuild, npCountSolutions, NP_DECOYS, NP_STAGE_CONFIG } from "../src/lib/duel/numberPyramid";

const SETS = 400;
const rand = (n: number) => Math.floor(Math.random() * n);
const shuffle = <T,>(a: T[]) => {
  for (let i = a.length - 1; i > 0; i--) { const j = rand(i + 1); [a[i], a[j]] = [a[j]!, a[i]!]; }
  return a;
};

type Built = { rows: 4 | 5; givens: (number | null)[]; tray: number[]; solution: number[]; empty: number };
function build(stage: (typeof NP_STAGE_CONFIG)[number]): Built | null {
  const bottom = Array.from({ length: stage.rows }, () => stage.bottomLo + rand(stage.bottomHi - stage.bottomLo + 1));
  const solution = npBuild(bottom);
  const empty = stage.minEmpty + rand(stage.maxEmpty - stage.minEmpty + 1);
  const cells = shuffle([...Array(solution.length).keys()]).slice(0, empty).sort((a, b) => a - b);
  const givens = solution.map((v, i) => (cells.includes(i) ? null : v));
  const lo = Math.min(...solution);
  const hi = Math.max(...solution);
  const missing = cells.map((c) => solution[c]!);
  const decoys: number[] = [];
  for (let tries = 0; decoys.length < NP_DECOYS && tries < 80; tries++) {
    const base = missing[rand(missing.length)]!;
    const d = base + (rand(2) ? 1 : -1) * (1 + rand(3));
    if (d < lo || d > hi || d < 1) continue;
    decoys.push(d);
  }
  if (decoys.length < NP_DECOYS) return null;
  const tray = shuffle([...missing, ...decoys]);
  if (npCountSolutions(givens, tray, stage.rows, 2) !== 1) return null;
  return { rows: stage.rows, givens, tray, solution, empty };
}

const sets: Built[][] = [];
const seen = new Set<string>();
let attempts = 0;
const t0 = performance.now();
while (sets.length < SETS) {
  const set: Built[] = [];
  let valid = true;
  for (const stage of NP_STAGE_CONFIG) {
    let board: Built | null = null;
    for (let tries = 0; tries < 500 && !board; tries++) {
      attempts++;
      const candidate = build(stage);
      if (!candidate) continue;
      const key = JSON.stringify(candidate.givens) + JSON.stringify([...candidate.tray].sort((a, b) => a - b));
      if (seen.has(key)) continue;
      seen.add(key);
      board = candidate;
    }
    if (!board) { valid = false; break; }
    set.push(board);
  }
  if (valid) sets.push(set);
}
const out = `/** Generated by scripts/number-pyramid-bank.ts. Every board has exactly one tray assignment. */\nexport interface NumberPyramidBankBoard { rows: 4 | 5; givens: (number | null)[]; tray: number[]; solution: number[]; }\nexport interface NumberPyramidBankEntry { pyramids: NumberPyramidBankBoard[]; }\nexport const NUMBER_PYRAMID_BANK: NumberPyramidBankEntry[] = ${JSON.stringify(sets.map((pyramids) => ({ pyramids: pyramids.map(({ rows, givens, tray, solution }) => ({ rows, givens, tray, solution })) })))};\n`;
writeFileSync(new URL("../src/lib/duel/numberPyramidBank.server.ts", import.meta.url), out);
console.log(`number pyramid bank: ${sets.length} sets / ${sets.length * 3} unique boards from ${attempts} attempts in ${((performance.now() - t0) / 1000).toFixed(1)}s`);
