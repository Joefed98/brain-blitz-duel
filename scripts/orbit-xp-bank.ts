/**
 * Builds the server-only Orbit feature bank (src/lib/duel/orbitXpBank.server.ts) for orbitRev 11 (world
 * expansion): for each black-hole bank course (ORBIT_HOLE_BANK), its stardust trails, slingshot moons and
 * asteroid fields, placed and proved by scripts/orbit-xp-lib.ts (buildXp), with the witness run's taps (every
 * hole and feature taken, the sun reached, 200) so orbit-rev11-check can re-verify every entry by replay.
 * Courses that cannot carry every feature are left out: rooms deal them orbitRev 10 as before.
 *
 * Deterministic: the same hole bank always gives the same features.
 *
 *   bun scripts/orbit-xp-bank.ts                         # build and write (8 workers)
 *   bun scripts/orbit-xp-bank.ts <from> <to> <out.json>  # one shard (worker mode)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { decodeOrbitHoles, decodeRev3Planets, encodeOrbitExtras, type OrbitExtrasRow } from "../src/lib/arcade/orbitRev3";
import { ORBIT_HOLE_BANK } from "../src/lib/duel/orbitHoleBank.server";
import { ORBIT_REV3_BANK } from "../src/lib/duel/orbitRev3Bank.server";
import { buildXp, xpFailure } from "./orbit-xp-lib";

const OUT = "src/lib/duel/orbitXpBank.server.ts";
const WORKERS = 8;

interface Entry {
  seed: number;
  extras: OrbitExtrasRow;
  taps: number[];
  ticks: number;
}

function buildRange(from: number, to: number): Entry[] {
  const out: Entry[] = [];
  for (let i = from; i < to && i < ORBIT_HOLE_BANK.length; i++) {
    const hole = ORBIT_HOLE_BANK[i]!;
    const course = ORBIT_REV3_BANK.find((e) => e.seed === hole.seed)!;
    const witness = buildXp(decodeRev3Planets(course.planets), decodeOrbitHoles(hole.holes), hole.seed);
    if (!witness) {
      console.log(`  course ${i} (seed ${hole.seed}): no features — ${xpFailure}`);
      continue;
    }
    out.push({ seed: hole.seed, extras: encodeOrbitExtras(witness.extras), taps: witness.taps, ticks: witness.ticks });
  }
  return out;
}

if (process.argv[4]) {
  const started = Date.now();
  const out = buildRange(Number(process.argv[2]), Number(process.argv[3]));
  console.log(`shard ${process.argv[2]}-${process.argv[3]}: ${out.length} courses with features in ${((Date.now() - started) / 1000).toFixed(1)} s`);
  writeFileSync(process.argv[4], JSON.stringify(out));
} else {
  const per = Math.ceil(ORBIT_HOLE_BANK.length / WORKERS);
  const parts = Array.from({ length: WORKERS }, (_, w) => `${process.env.TMPDIR ?? "/tmp"}/orbit-xp-part-${w}.json`);
  const started = Date.now();
  const procs = parts.map((file, w) =>
    Bun.spawn(["bun", "run", "scripts/orbit-xp-bank.ts", String(w * per), String((w + 1) * per), file], { stdout: "inherit", stderr: "inherit" }),
  );
  const codes = await Promise.all(procs.map((p) => p.exited));
  codes.forEach((code, i) => {
    if (code !== 0) throw new Error(`worker ${i} exited ${code}`);
  });
  const entries = parts.flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as Entry[]);
  writeFileSync(
    OUT,
    `/* Generated by scripts/orbit-xp-bank.ts — do not edit by hand. */\nimport type { OrbitExtrasRow } from "@/lib/arcade/orbitRev3";\n\nexport interface OrbitXpBankEntry {\n  /** The black-hole bank course (ORBIT_HOLE_BANK, ORBIT_REV3_BANK) these features belong to. */\n  seed: number;\n  /** Stardust trails, slingshot moons and asteroid fields (see decodeOrbitExtras). */\n  extras: OrbitExtrasRow;\n  /** Witness taps: a run that takes every hole and feature and reaches the sun (orbitRev 11's 200). */\n  taps: number[];\n  /** The witness run's finishing tick. */\n  ticks: number;\n}\n\nexport const ORBIT_XP_BANK: OrbitXpBankEntry[] = ${JSON.stringify(entries)};\n`,
  );
  console.log(`wrote ${entries.length} / ${ORBIT_HOLE_BANK.length} courses with features to ${OUT} in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}
