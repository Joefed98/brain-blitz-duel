/**
 * Writes src/lib/duel/catalogue.data.ts and src/lib/duel/gameModules.ts from the full registry (speed fix 1, Nov 2026): every game's id,
 * name, category, clock and reveal fields, in the registry's order, so the menus, lists and timing
 * helpers read them without downloading a single game.
 *
 *   bun scripts/game-catalogue.ts           rewrite the file
 *   bun scripts/game-catalogue.ts --check   fail if the file differs from what the registry gives
 *
 * Re-run it after adding a game or changing a definition's name, category, timeLimitMs, revealMs,
 * arcadeRun, showTimer or revealHeading, or a GOAL line in instructions.ts (game-catalogue-check fails until
 * then).
 */
import { readFileSync, writeFileSync } from "node:fs";

import { BASE_REGISTRY } from "../src/lib/duel/registry";
import { PUZZLE_INSTRUCTIONS } from "../src/lib/duel/instructions";

const FILE = "src/lib/duel/catalogue.data.ts";
const MODULES_FILE = "src/lib/duel/gameModules.ts";

/** The per-game loaders, read from registry.ts's own imports (`import { x } from "@/puzzles/m"`, `type: x,`). */
export function modulesSource(): string {
  const src = readFileSync("src/lib/duel/registry.ts", "utf8");
  const moduleOf = new Map<string, string>();
  for (const m of src.matchAll(/^import \{ (\w+) \} from "@\/puzzles\/([\w-]+)";$/gm)) moduleOf.set(m[1]!, m[2]!);
  const lines: string[] = [];
  for (const [type, def] of Object.entries(BASE_REGISTRY)) {
    const ident = new RegExp(`\\n\\s*${type}:\\s*(\\w+),`).exec(src.slice(src.indexOf("BASE_REGISTRY")))?.[1];
    const mod = ident ? moduleOf.get(ident) : undefined;
    if (!ident || !mod) throw new Error(`${type}: no import found in registry.ts`);
    if (def.key !== type) throw new Error(`${type}: key ${def.key}`);
    lines.push(`  ${type}: () => import("@/puzzles/${mod}").then((m) => m.${ident}),`);
  }
  return [
    "// Generated by scripts/game-catalogue.ts from src/lib/duel/registry.ts; do not edit by hand.",
    "// One dynamic import per game, so the phone downloads a game's code only when it is first needed",
    "// (gameLoader.ts). game-catalogue-check proves each loader gives the registry's own definition.",
    'import type { PuzzleDefinition } from "@/puzzles/types";',
    'import type { PuzzleType } from "./types";',
    "",
    'export type GameModuleDefinition = Omit<PuzzleDefinition, "instructions">;',
    "",
    "export const GAME_MODULES: Record<PuzzleType, () => Promise<GameModuleDefinition>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

export function catalogueSource(): string {
  const lines: string[] = [];
  for (const [type, def] of Object.entries(BASE_REGISTRY)) {
    const fields: string[] = [
      `name: ${JSON.stringify(def.name)}`,
      `category: ${JSON.stringify(def.category)}`,
      `timeLimitMs: ${def.timeLimitMs}`,
    ];
    if (def.revealMs !== undefined) fields.push(`revealMs: ${def.revealMs}`);
    if (def.arcadeRun !== undefined) fields.push(`arcadeRun: ${def.arcadeRun}`);
    if (def.showTimer !== undefined) fields.push(`showTimer: ${def.showTimer}`);
    if (def.revealHeading !== undefined) fields.push(`revealHeading: ${JSON.stringify(def.revealHeading)}`);
    // The intro's GOAL line (instructions.ts), for the play header's goal line without the help copy.
    const goal = PUZZLE_INSTRUCTIONS[type as keyof typeof PUZZLE_INSTRUCTIONS]?.goal;
    if (goal !== undefined) fields.push(`goal: ${JSON.stringify(goal)}`);
    if (def.prepMs || def.durationMs) throw new Error(`${type}: prepMs / durationMs are not in the catalogue yet`);
    if (def.key !== type) throw new Error(`${type}: key ${def.key}`);
    lines.push(`  ${type}: { ${fields.join(", ")} },`);
  }
  return [
    "// Generated by scripts/game-catalogue.ts from src/lib/duel/registry.ts; do not edit by hand.",
    "// game-catalogue-check proves it matches the registry.",
    'import type { PuzzleType } from "./types";',
    'import type { CatalogueEntry } from "./catalogue";',
    "",
    "export const CATALOGUE_DATA: Record<PuzzleType, CatalogueEntry> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  for (const [file, next] of [
    [FILE, catalogueSource()],
    [MODULES_FILE, modulesSource()],
  ] as const) {
    if (process.argv.includes("--check")) {
      const now = readFileSync(file, "utf8");
      if (now !== next) {
        console.log(`FAIL ${file} is out of date: run bun scripts/game-catalogue.ts`);
        process.exit(1);
      }
      console.log(`${file} matches the registry`);
    } else {
      writeFileSync(file, next);
      console.log(`wrote ${file}`);
    }
  }
}
