/**
 * Customise's game-look pictures (12 Nov 2026, the Games tab): every card back, game skin and world theme's approved
 * still (docs/art/wave-2/items/<kind>/<name>.png, 2x, as it looks under Reduce Motion) scaled to at most PREVIEW_W
 * pixels wide and encoded as WebP into public/looks/<id>.webp, plus src/lib/skins/lookPreviews.data.ts (each id's
 * content hash, put on its URL). The shop keeps its own pictures (scripts/shop-previews.ts, shop items only); these
 * cover every look item, pass items included, so an owned item always has its picture.
 *
 *   bun scripts/look-previews.ts            write them
 *   bun scripts/look-previews.ts --check    fail unless the data file matches the images on disk and every look item has one
 *
 * Re-run it after an item's approved art changes. The same bytes every run (no timestamps).
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { createCanvas, loadImage } from "@napi-rs/canvas";

const PREVIEW_W = 240;
const QUALITY = 82;
const OUT_DIR = "public/looks";
const DATA = "src/lib/skins/lookPreviews.data.ts";
const KINDS = new Set(["card-back", "game-skin", "world-theme"]);

interface JsonItem {
  id: string;
  kind: string;
  png: string;
}
const items = (JSON.parse(readFileSync("docs/art/wave-2/catalogue.json", "utf8")) as { items: JsonItem[] }).items.filter((i) =>
  KINDS.has(i.kind),
);

function dataFile(): string {
  const lines = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".webp"))
    .sort()
    .map((f) => {
      const hash = createHash("sha256").update(readFileSync(join(OUT_DIR, f))).digest("hex").slice(0, 10);
      return `  ${JSON.stringify(f.replace(/\.webp$/, ""))}: "${hash}",`;
    });
  return `/**
 * Generated by \`bun scripts/look-previews.ts\`; do not edit. Each card back, game skin and world theme's picture
 * (public/looks/<id>.webp, from its approved still in docs/art/wave-2/items) and the picture's content hash, put on
 * its URL (Customise's Games tab).
 */
export const LOOK_PREVIEWS: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`;
}

if (process.argv.includes("--check")) {
  const missing = items.filter((i) => !existsSync(join(OUT_DIR, `${i.id}.webp`))).map((i) => i.id);
  const stale = !existsSync(DATA) || readFileSync(DATA, "utf8") !== dataFile();
  if (missing.length || stale) {
    console.log(`look-previews: FAIL${missing.length ? ` missing ${missing.join(", ")}` : ""}${stale ? " (data file out of date)" : ""}`);
    process.exit(1);
  }
  console.log(`look-previews: ${items.length} pictures, data file current`);
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
let total = 0;
for (const item of items) {
  const img = await loadImage(readFileSync(join("docs/art/wave-2", item.png)));
  const scale = Math.min(1, PREVIEW_W / img.width);
  const w = Math.round(img.width * scale);
  const h = Math.round(img.height * scale);
  const canvas = createCanvas(w, h);
  const ctx = canvas.getContext("2d");
  ctx.imageSmoothingQuality = "high";
  ctx.drawImage(img, 0, 0, w, h);
  const webp = await canvas.encode("webp", QUALITY);
  writeFileSync(join(OUT_DIR, `${item.id}.webp`), webp);
  total += webp.length;
}
writeFileSync(DATA, dataFile());
console.log(`look-previews: ${items.length} pictures, ${Math.round(total / 1024)} KB`);
