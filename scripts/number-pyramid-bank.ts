/**
 * Builds the Number Pyramid bank in src/lib/duel/numberPyramidBank.server.ts.
 *
 *   bun scripts/number-pyramid-bank.ts
 *
 * Answer-first: a bottom row of 1–9 (duplicates allowed) fixes the pyramid;
 * 6–9 cells are emptied; the tray is their values plus two decoys, each a
 * near neighbour (±1–3) of a missing value inside the pyramid's value range.
 * A full search over tray assignments must find exactly one filling.
 */
import { writeFileSync } from "node:fs";

import {
  npBuild,
  npCountSolutions,
  NP_CELLS,
  NP_DECOYS,
  NP_MAX_EMPTY,
  NP_MIN_EMPTY,
  NP_ROWS,
} from "../src/lib/duel/numberPyramid";

const BANK = 400;
const rand = (n: number) => Math.floor(Math.random() * n);
const shuffle = <T,>(a: T[]) => {
  for (let i = a.length - 1; i > 0; i--) {
    const j = rand(i + 1);
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
};

function build() {
  const bottom = Array.from({ length: NP_ROWS }, () => 1 + rand(9));
  const solution = npBuild(bottom);
  const empty = NP_MIN_EMPTY + rand(NP_MAX_EMPTY - NP_MIN_EMPTY + 1);
  const cells = shuffle([...Array(NP_CELLS).keys()]).slice(0, empty).sort((a, b) => a - b);
  const givens: (number | null)[] = solution.map((v, i) => (cells.includes(i) ? null : v));
  const lo = Math.min(...solution);
  const hi = Math.max(...solution);
  const missing = cells.map((c) => solution[c]!);
  const decoys: number[] = [];
  for (let tries = 0; decoys.length < NP_DECOYS && tries < 50; tries++) {
    const base = missing[rand(missing.length)]!;
    const d = base + (rand(2) ? 1 : -1) * (1 + rand(3));
    if (d < lo || d > hi || d < 1) continue;
    decoys.push(d);
  }
  if (decoys.length < NP_DECOYS) return null;
  const tray = shuffle([...missing, ...decoys]);
  if (npCountSolutions(givens, tray, 2) !== 1) return null;
  return { givens, tray, solution, empty, decoys };
}

const bank: NonNullable<ReturnType<typeof build>>[] = [];
const seen = new Set<string>();
let attempts = 0;
const t0 = performance.now();
while (bank.length < BANK) {
  attempts++;
  const p = build();
  if (!p) continue;
  const key = JSON.stringify(p.givens) + JSON.stringify([...p.tray].sort((a, b) => a - b));
  if (seen.has(key)) continue;
  seen.add(key);
  bank.push(p);
}
const byEmpty = [6, 7, 8, 9].map((n) => `${n}:${bank.filter((b) => b.empty === n).length}`).join(" ");
const out = `/**
 * Number Pyramid bank — generated by scripts/number-pyramid-bank.ts. Each entry
 * was proven by a full search over tray assignments: exactly one filling of the
 * empty cells satisfies every sum rule, and it never uses the two decoys.
 * Do not edit by hand.
 */

export interface NumberPyramidBankEntry {
  /** Given values; null = empty cell. */
  givens: (number | null)[];
  /** The empty cells' values plus two decoys, already shuffled. */
  tray: number[];
  solution: number[];
}

export const NUMBER_PYRAMID_BANK: NumberPyramidBankEntry[] = ${JSON.stringify(bank.map(({ givens, tray, solution }) => ({ givens, tray, solution })))};
`;
writeFileSync(new URL("../src/lib/duel/numberPyramidBank.server.ts", import.meta.url), out);
console.log(`number pyramid bank: ${bank.length} from ${attempts} attempts in ${((performance.now() - t0) / 1000).toFixed(1)}s · empty cells ${byEmpty}`);
