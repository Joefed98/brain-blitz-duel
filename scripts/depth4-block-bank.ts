/**
 * Builds Tessellate's 7×7 bank (blockRev 1, depth batch 4; docs/depth/d4-pattern.md) in
 * src/lib/duel/depth4/blockD4Bank.server.ts. Entry i is generateBlockD4() under the fixed seed
 * hash("blockD4", i, retry), the first retry that gives a new in-band board, so the bank rebuilds byte for
 * byte. Runs on four worker processes.
 *
 *   bun scripts/depth4-block-bank.ts            # build and write
 *   bun scripts/depth4-block-bank.ts --check    # rebuild a sample and compare, no write
 */
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { generateBlockD4 } from "../src/lib/duel/depth4/blockD4";
import { withSeededRandom } from "../src/lib/duel/random";
import type { BlockPartyPuzzleData } from "../src/lib/duel/types";

export const BLOCK_D4_BANK_SIZE = 1000;

export function blockD4Seed(index: number, retry: number): number {
  let h = 2166136261;
  for (const ch of `blockD4:${index}:${retry}`) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return h >>> 0;
}

/** Entry `index` at `retry` (null when that seed finds no in-band board in its attempts). */
export function blockD4Candidate(index: number, retry: number): BlockPartyPuzzleData | null {
  return withSeededRandom(blockD4Seed(index, retry), () => generateBlockD4(60));
}

function firstCandidate(index: number, from = 0): { retry: number; puzzle: BlockPartyPuzzleData } {
  for (let retry = from; ; retry++) {
    const puzzle = blockD4Candidate(index, retry);
    if (puzzle) return { retry, puzzle };
  }
}

const args = process.argv.slice(2);
if (args[0] === "--worker") {
  const [k, n] = [Number(args[1]), Number(args[2])];
  for (let i = k; i < BLOCK_D4_BANK_SIZE; i += n) console.log(JSON.stringify({ index: i, ...firstCandidate(i) }));
  process.exit(0);
}

if (import.meta.main) {
  const n = 4;
  const found: { index: number; retry: number; puzzle: BlockPartyPuzzleData }[] = [];
  await Promise.all(
    Array.from({ length: n }, (_, k) =>
      new Promise<void>((resolve, reject) => {
        const child = spawn("bun", [import.meta.path, "--worker", String(k), String(n)], { stdio: ["ignore", "pipe", "inherit"] });
        let buf = "";
        child.stdout.setEncoding("utf8");
        child.stdout.on("data", (chunk: string) => {
          buf += chunk;
          let nl: number;
          while ((nl = buf.indexOf("\n")) >= 0) {
            const line = buf.slice(0, nl);
            buf = buf.slice(nl + 1);
            if (line.trim()) {
              found.push(JSON.parse(line));
              if (found.length % 100 === 0) console.error(`${found.length}/${BLOCK_D4_BANK_SIZE}`);
            }
          }
        });
        child.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`worker ${k} exited ${code}`))));
      }),
    ),
  );
  found.sort((a, b) => a.index - b.index);
  // A duplicate board moves the later index on to its next retry.
  const seen = new Set<string>();
  for (const entry of found) {
    let e = entry;
    while (seen.has(e.puzzle.blockers.join(","))) e = { index: e.index, ...firstCandidate(e.index, e.retry + 1) };
    seen.add(e.puzzle.blockers.join(","));
    Object.assign(entry, e);
  }
  if (args.includes("--check")) {
    const { BLOCK_D4_BANK } = await import("../src/lib/duel/depth4/blockD4Bank.server");
    const same = found.every((e, i) => JSON.stringify(e.puzzle) === JSON.stringify(BLOCK_D4_BANK[i]));
    console.log(same ? "blockD4 bank rebuilds identically" : "FAIL: blockD4 bank differs");
    process.exit(same ? 0 : 1);
  }
  const source = `/* Generated by scripts/depth4-block-bank.ts — do not edit by hand. Rebuild with \`bun scripts/depth4-block-bank.ts\`. */
import type { BlockPartyPuzzleData } from "../types";

/** Tessellate's 7×7 boards (blockRev 1): fifteen pegs, ten pieces, 5–60 solutions each. */
export const BLOCK_D4_RETRIES: number[] = [${found.map((e) => e.retry).join(",")}];

export const BLOCK_D4_BANK: BlockPartyPuzzleData[] = [
${found.map((e) => `  ${JSON.stringify(e.puzzle)},`).join("\n")}
];
`;
  writeFileSync("src/lib/duel/depth4/blockD4Bank.server.ts", source);
  console.log(`${found.length} boards written`);
}
