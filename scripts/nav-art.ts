/**
 * The navigation's art (phase 2 step 1, 14 Nov 2026): the style guide's 3D art-kit icons
 * (docs/design/style-guide/art/*.png, 192 px renders) cut to the sizes the navigation draws, at 1x, 2x and 3x, as
 * WebP in public/nav/, plus src/components/nav/navArt.data.ts (each image's url with its content hash, its size and
 * the alt text). Never upscaled: a 3x past the 192 px source is left out (the browser takes the 2x).
 *
 *   bun scripts/nav-art.ts          rebuild
 *   bun scripts/nav-art.ts --check  rebuild in memory and fail if anything on disk differs (nav-art-check)
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/nav");
const DATA = join(ROOT, "src/components/nav/navArt.data.ts");

/** Every image the navigation draws: its art-kit source, the CSS px it is drawn at, and what it shows. */
export const NAV_ART = {
  home: { src: "home", px: 28, alt: "Home" },
  games: { src: "games", px: 28, alt: "Games" },
  tournaments: { src: "trophy", px: 28, alt: "Tournaments" },
  shop: { src: "shop", px: 28, alt: "Shop" },
  more: { src: "more", px: 28, alt: "More" },
  profile: { src: "profile", px: 40, alt: "Profile" },
  friends: { src: "friends", px: 40, alt: "Friends" },
  leaderboards: { src: "leaderboards", px: 40, alt: "Leaderboards" },
  challenges: { src: "challenges", px: 40, alt: "Challenges" },
  daily: { src: "daily", px: 40, alt: "Daily" },
  plus: { src: "plus", px: 40, alt: "Joulz Plus" },
  settings: { src: "settings", px: 40, alt: "Settings" },
  support: { src: "support", px: 40, alt: "Support" },
  trophyHero: { src: "trophy", px: 96, alt: "A gold trophy" },
  bolt: { src: "joules", px: 96, alt: "The Joulz bolt" },
} as const;

export type NavArtName = keyof typeof NAV_ART;

async function build(): Promise<{ files: Map<string, Buffer>; data: string }> {
  const files = new Map<string, Buffer>();
  const entries: string[] = [];
  for (const [name, spec] of Object.entries(NAV_ART)) {
    const image = await loadImage(readFileSync(join(SOURCE, `${spec.src}.png`)));
    const urls: string[] = [];
    for (const scale of [1, 2, 3]) {
      const size = spec.px * scale;
      if (size > image.width) continue;
      const canvas = createCanvas(size, size);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, size, size);
      const bytes = Buffer.from(await canvas.encode("webp", 88));
      const file = `${name}-${scale}x.webp`;
      files.set(file, bytes);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      urls.push(`"/nav/${file}?v=${hash}"`);
    }
    entries.push(`  ${name}: { px: ${spec.px}, alt: ${JSON.stringify(spec.alt)}, urls: [${urls.join(", ")}] },`);
  }
  const data = `// Generated by scripts/nav-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x, 2x and (where the 192 px source allows) 3x WebP.\nexport const NAV_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type NavArtName = keyof typeof NAV_ART;\n`;
  return { files, data };
}

const check = process.argv.includes("--check");
const { files, data } = await build();
let total = 0;
for (const b of files.values()) total += b.length;
if (check) {
  const problems: string[] = [];
  for (const [file, bytes] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) problems.push(`public/nav/${file} differs`);
  }
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("navArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/nav-art.ts)`);
    process.exit(1);
  }
  console.log(`nav art matches: ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
}
