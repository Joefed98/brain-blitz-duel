/**
 * Home and Play's art (phase 2 step 3, the Home and Play pages, 14 Nov 2026): the style guide's 3D art-kit renders
 * (docs/design/style-guide/art/*.png: 192 px icons, 640 × 400 key art, the 960 × 600 hero) cut to the sizes Home, Play
 * and Rooms draw, at 1x, 2x and (where the source allows) 3x, as WebP in public/home/, plus
 * src/components/home/homeArt.data.ts (each image's urls with their content hash, its CSS size and alt text). Never
 * upscaled: a scale past the source is left out (the browser takes the largest there is).
 *
 *   bun scripts/home-art.ts          rebuild
 *   bun scripts/home-art.ts --check  rebuild in memory and fail if anything on disk differs (home-art-check)
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/home");
const DATA = join(ROOT, "src/components/home/homeArt.data.ts");

/** Every image: its art-kit source, the CSS size it is drawn at (w × h) and what it shows. */
export const HOME_ART = {
  playHero: { src: "key-hero", w: 480, h: 300, alt: "The Joulz bolt on a stand with a puzzle block and a ball" },
  dailyPuzzle: { src: "key-board", w: 200, h: 125, alt: "A board of coloured puzzle blocks" },
  dailyArcade: { src: "arcade", w: 64, h: 64, alt: "An arcade joystick" },
  arena: { src: "arena", w: 44, h: 44, alt: "Arena" },
  rooms: { src: "rooms", w: 44, h: 44, alt: "Rooms" },
  practice: { src: "practice", w: 44, h: 44, alt: "Practice" },
  daily: { src: "daily", w: 44, h: 44, alt: "Daily" },
  rated: { src: "rated", w: 32, h: 32, alt: "Rated" },
  joulz: { src: "joules", w: 44, h: 44, alt: "Joulz Rating" },
  puzzles: { src: "puzzles", w: 44, h: 44, alt: "Puzzles" },
  arcade: { src: "arcade", w: 44, h: 44, alt: "Arcade" },
  week: { src: "quest", w: 44, h: 44, alt: "This week" },
  friends: { src: "friends", w: 44, h: 44, alt: "Friends" },
} as const;

export type HomeArtName = keyof typeof HOME_ART;

async function build(): Promise<{ files: Map<string, Buffer>; data: string }> {
  const files = new Map<string, Buffer>();
  const entries: string[] = [];
  for (const [name, spec] of Object.entries(HOME_ART)) {
    const image = await loadImage(readFileSync(join(SOURCE, `${spec.src}.png`)));
    const urls: string[] = [];
    for (const scale of [1, 2, 3]) {
      const w = spec.w * scale;
      const h = spec.h * scale;
      if (w > image.width || h > image.height) continue;
      const canvas = createCanvas(w, h);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, w, h);
      const bytes = Buffer.from(await canvas.encode("webp", 86));
      const file = `${name}-${scale}x.webp`;
      files.set(file, bytes);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      urls.push(`"/home/${file}?v=${hash}"`);
    }
    entries.push(`  ${name}: { w: ${spec.w}, h: ${spec.h}, alt: ${JSON.stringify(spec.alt)}, urls: [${urls.join(", ")}] },`);
  }
  const data = `// Generated by scripts/home-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x, 2x and (where the source allows) 3x WebP.\nexport const HOME_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type HomeArtName = keyof typeof HOME_ART;\n`;
  return { files, data };
}

const check = process.argv.includes("--check");
const { files, data } = await build();
let total = 0;
for (const b of files.values()) total += b.length;
if (check) {
  const problems: string[] = [];
  for (const [file, bytes] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) problems.push(`public/home/${file} differs`);
  }
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("homeArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/home-art.ts)`);
    process.exit(1);
  }
  console.log(`PASS home art matches: ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
}
