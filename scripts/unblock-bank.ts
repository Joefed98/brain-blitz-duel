/**
 * Builds the Unblock layout bank. Every layout is solved by breadth-first
 * search, so the stored minimum move count is the true minimum. Run with:
 *   bun run scripts/unblock-bank.ts
 * It rewrites src/lib/duel/unblockBank.server.ts.
 */

import { writeFileSync } from "node:fs";

const N = 6;
const EXIT_ROW = 2;

interface V {
  id: number;
  row: number;
  col: number;
  len: number;
  axis: "h" | "v";
}

function cells(v: V): number[] {
  return Array.from({ length: v.len }, (_, i) =>
    v.axis === "h" ? v.row * N + v.col + i : (v.row + i) * N + v.col,
  );
}

function occupied(vs: V[], skip?: number): Set<number> {
  const out = new Set<number>();
  for (const v of vs) {
    if (v.id === skip) continue;
    for (const c of cells(v)) out.add(c);
  }
  return out;
}

function pos(v: V): number {
  return v.axis === "h" ? v.col : v.row;
}

function moved(v: V, to: number): V {
  return v.axis === "h" ? { ...v, col: to } : { ...v, row: to };
}

function range(vs: V[], id: number): [number, number] {
  const v = vs.find((e) => e.id === id)!;
  const blocked = occupied(vs, id);
  let min = pos(v);
  while (min - 1 >= 0) {
    const cell = v.axis === "h" ? v.row * N + (min - 1) : (min - 1) * N + v.col;
    if (blocked.has(cell)) break;
    min -= 1;
  }
  let max = pos(v);
  while (max + v.len <= N - 1) {
    const next = max + v.len;
    const cell = v.axis === "h" ? v.row * N + next : next * N + v.col;
    if (blocked.has(cell)) break;
    max += 1;
  }
  return [min, max];
}

const solved = (vs: V[]) => {
  const gold = vs[0]!;
  return gold.col + gold.len === N;
};

const key = (vs: V[]) => vs.map(pos).join(".");

/** Fewest moves to free the gold car, or null when the layout cannot be solved. */
function minMoves(start: V[]): number | null {
  if (solved(start)) return 0;
  const seen = new Set<string>([key(start)]);
  let frontier: V[][] = [start];
  for (let depth = 1; depth <= 40; depth++) {
    const next: V[][] = [];
    for (const state of frontier) {
      for (const v of state) {
        const [min, max] = range(state, v.id);
        for (let to = min; to <= max; to++) {
          if (to === pos(v)) continue;
          const child = state.map((e) => (e.id === v.id ? moved(e, to) : e));
          const k = key(child);
          if (seen.has(k)) continue;
          seen.add(k);
          if (solved(child)) return depth;
          next.push(child);
        }
      }
    }
    if (next.length === 0) return null;
    frontier = next;
  }
  return null;
}

function randomLayout(): V[] | null {
  const gold: V = { id: 0, row: EXIT_ROW, col: Math.floor(Math.random() * 3), len: 2, axis: "h" };
  const vs: V[] = [gold];
  const taken = new Set<number>(cells(gold));
  const wanted = 8 + Math.floor(Math.random() * 5);

  for (let attempt = 0; attempt < 400 && vs.length < wanted + 1; attempt++) {
    const axis = Math.random() < 0.5 ? "h" : "v";
    const len = Math.random() < 0.68 ? 2 : 3;
    const row = Math.floor(Math.random() * (axis === "v" ? N - len + 1 : N));
    const col = Math.floor(Math.random() * (axis === "h" ? N - len + 1 : N));
    if (axis === "h" && row === EXIT_ROW) continue; // nothing else lies on the exit row
    const candidate: V = { id: vs.length, row, col, len, axis };
    const spots = cells(candidate);
    if (spots.some((c) => taken.has(c))) continue;
    for (const c of spots) taken.add(c);
    vs.push(candidate);
  }
  return vs.length >= 7 ? vs : null;
}

const serialise = (vs: V[]) => vs.map((v) => `${v.id}${v.axis}${v.len}${v.row}${v.col}`).join(",");

const buckets: { name: string; low: number; high: number; want: number; out: string[] }[] = [
  { name: "easy", low: 6, high: 8, want: 40, out: [] },
  { name: "medium", low: 9, high: 12, want: 40, out: [] },
  { name: "hard", low: 13, high: 18, want: 40, out: [] },
];

const seen = new Set<string>();
let tried = 0;
while (buckets.some((b) => b.out.length < b.want) && tried < 400_000) {
  tried += 1;
  const layout = randomLayout();
  if (!layout) continue;
  const line = serialise(layout);
  if (seen.has(line)) continue;
  seen.add(line);
  const min = minMoves(layout);
  if (min === null) continue;
  const bucket = buckets.find((b) => min >= b.low && min <= b.high && b.out.length < b.want);
  if (!bucket) continue;
  bucket.out.push(`${line}|${min}`);
}

for (const bucket of buckets) {
  console.log(`${bucket.name}: ${bucket.out.length} layouts`);
}

const body = `/**
 * Unblock layout bank — generated by scripts/unblock-bank.ts. Each entry is the
 * layout followed by its verified minimum move count. Never edit by hand.
 */

/** 6-8 moves. */
export const UNBLOCK_EASY: string[] = [
${buckets[0]!.out.map((l) => `  "${l}",`).join("\n")}
];

/** 9-12 moves. */
export const UNBLOCK_MEDIUM: string[] = [
${buckets[1]!.out.map((l) => `  "${l}",`).join("\n")}
];

/** 13-18 moves. */
export const UNBLOCK_HARD: string[] = [
${buckets[2]!.out.map((l) => `  "${l}",`).join("\n")}
];

export const UNBLOCK_BANK: string[] = [...UNBLOCK_EASY, ...UNBLOCK_MEDIUM, ...UNBLOCK_HARD];
`;

writeFileSync("src/lib/duel/unblockBank.server.ts", body);
console.log(`tried ${tried} layouts`);
