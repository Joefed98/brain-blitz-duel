/** Precompute 400 answer-first pipe boards. Each row of eight balls must stay a
 * permutation (otherwise two paths merge permanently and eight unique buckets
 * cannot be reached). Thus its only legal row mappings are disjoint adjacent
 * swaps or verticals. The sum of the cheapest matching cost per row is a
 * rigorous lower bound; accepted answer-first layouts attain it exactly. */
import { writeFileSync } from 'node:fs';
import { BT_COLS, BT_ROWS, btRun } from '../src/lib/duel/ballTrack';

let seed = 0x41b4c7;
const random = () => (seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296;
const pick = (n: number) => Math.floor(random() * n);
const matchings: string[] = [];
function build(prefix: string) {
  if (prefix.length === BT_COLS) { matchings.push(prefix); return; }
  build(prefix + '0');
  if (prefix.length < BT_COLS - 1) build(prefix + '12');
}
build('');
const cost = (from: string, to: string) => [...from].reduce((n, value, index) => n + (Number(to[index]) - Number(value) + 3) % 3, 0);
const entries: { tiles: string; buckets: number[]; min: number; solution: string }[] = [];
const seen = new Set<string>();
for (let attempt = 0; entries.length < 400 && attempt < 400_000; attempt++) {
  const answer = Array.from({ length: BT_ROWS }, () => matchings[pick(matchings.length)]!);
  const target = Array.from({ length: BT_COLS }, (_, i) => i);
  for (const row of answer) for (let i = 0; i < BT_COLS; i++) target[i] = target[i]! + (row[target[i]!] === '1' ? 1 : row[target[i]!] === '2' ? -1 : 0);
  if (target.some((column, ball) => column === ball)) continue;
  const buckets = Array.from({ length: BT_COLS }, () => -1);
  target.forEach((column, ball) => { buckets[column] = ball; });
  const scrambled: string[] = [];
  let rotations = 0;
  let lower = 0;
  for (const row of answer) {
    const start = [...row].map((digit) => String((Number(digit) + (pick(8) < 3 ? 1 : 0)) % 3)).join('');
    scrambled.push(start);
    rotations += cost(start, row);
    lower += Math.min(...matchings.map((matching) => cost(start, matching)));
  }
  if (rotations !== lower || rotations < 10 || rotations > 16) continue;
  const tiles = scrambled.join('');
  const solution = answer.join('');
  if (seen.has(tiles + buckets.join(''))) continue;
  const board = { cols: BT_COLS, rows: BT_ROWS, tiles, buckets };
  if (!target.every((column, ball) => btRun(board, solution, ball).bucket === column)) throw Error('Invalid answer-first paths');
  seen.add(tiles + buckets.join(''));
  entries.push({ tiles, buckets, min: rotations, solution });
}
if (entries.length !== 400) throw Error(`Only built ${entries.length} boards`);
const output = `/** Generated by scripts/ball-track-bank.ts; do not hand-edit.\n * Each minimum is proven by the per-row perfect-matching lower bound. */\nexport interface BallTrackBankEntry { tiles: string; buckets: number[]; min: number; solution: string }\nexport const BALL_TRACK_BANK: BallTrackBankEntry[] = ${JSON.stringify(entries)};\n`;
writeFileSync('src/lib/duel/ballTrackBank.server.ts', output);
console.log(`Ball Track: ${entries.length} boards; minimum rotations ${Math.min(...entries.map(e => e.min))}–${Math.max(...entries.map(e => e.min))}; ${seen.size} distinct`);
