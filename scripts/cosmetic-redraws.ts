/**
 * Builds the cosmetics redraws' art (phase 2 step 4, docs/design/cosmetics-redraws/) into
 * src/design/identity/redrawnArt.data.ts, beside today's art (playerCardArt.data.ts, cosmeticsArt.data.ts), in the same
 * shapes, so the same components draw either. Which one an item draws is its switch in src/config/cosmeticRedraws.ts
 * (src/design/identity/liveArt.ts merges them).
 *
 * Sources: scripts/cosmetic-redraws/*.ts (the compositions) and docs/design/cosmetics-redraws/source (the 3D pieces:
 * render.html, the art kit's raymarcher, and scenes.ts; render.ts writes public/cosmetics/redrawn/<piece>.webp).
 *
 *   bun scripts/cosmetic-redraws.ts           writes the data file
 *   bun scripts/cosmetic-redraws.ts --check   fails if the file is not what the sources build, or a piece is missing
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { buildCardPieces } from "./cosmetic-redraws/card";
import { buildCosmetics } from "./cosmetic-redraws/cosmetics";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "src/design/identity/redrawnArt.data.ts");

const card = buildCardPieces();
const cos = buildCosmetics();
const images = [...new Set([...card.images, ...cos.images])].sort();
const missing = images.filter((i) => !existsSync(join(ROOT, "public/cosmetics/redrawn", `${i}.webp`)));
if (missing.length) {
  console.error(`cosmetic-redraws: missing pieces (run docs/design/cosmetics-redraws/source/render.ts): ${missing.join(", ")}`);
  process.exit(1);
}

const j = (v: unknown) => JSON.stringify(v, null, 1);
const text =
  `/* Generated by scripts/cosmetic-redraws.ts from scripts/cosmetic-redraws and docs/design/cosmetics-redraws/source. Do not edit. */\n` +
  `import type { FinishArt } from "./cosmeticsArt.data";\n\n` +
  `/** Redrawn card arts (the card svg's inside, as CARD_ARTS). */\n` +
  `export const REDRAWN_CARD_ARTS: Record<string, string> = ${j(card.cardArts)};\n\n` +
  `/** Redrawn frames (as FRAMES). */\n` +
  `export const REDRAWN_FRAMES: Record<string, { markup: string; style: Record<string, string> }> = ${j(card.frames)};\n\n` +
  `/** Redrawn name colours (as NAME_COLOURS). */\n` +
  `export const REDRAWN_NAME_COLOURS: Record<string, { className: string; style: Record<string, string> }> = ${j(card.names)};\n\n` +
  `/** Each redrawn card piece's motion (scoped to .pcard; every rule stops under prefers-reduced-motion). */\n` +
  `export const REDRAWN_CARD_CSS: Record<string, string> = ${j(card.css)};\n\n` +
  `/** Redrawn avatar finishes (as FINISHES). */\n` +
  `export const REDRAWN_FINISHES: Record<string, FinishArt> = ${j(cos.finishes)};\n\n` +
  `/** Redrawn accessories (as ACCESSORIES). */\n` +
  `export const REDRAWN_ACCESSORIES: Record<string, string> = ${j(cos.accessories)};\n\n` +
  `/** Redrawn reaction packs (as REACTIONS). */\n` +
  `export const REDRAWN_REACTIONS: Record<string, readonly { svg: string; label: string }[]> = ${j(cos.reactions)};\n\n` +
  `/** Redrawn celebrations (as CELEBRATIONS). */\n` +
  `export const REDRAWN_CELEBRATIONS: Record<string, { svg: string; sample: string }> = ${j(cos.celebrations)};\n\n` +
  `/** Redrawn tile styles (as TILE_STYLES). */\n` +
  `export const REDRAWN_TILE_STYLES: Record<string, { back: string; front: string; sample: string }> = ${j(cos.tiles)};\n\n` +
  `/** Each redrawn cosmetic's motion (scoped to .jzc; every rule stops under prefers-reduced-motion). */\n` +
  `export const REDRAWN_COSMETICS_CSS: Record<string, string> = ${j(cos.css)};\n\n` +
  `/** Every 3D piece the redraws draw (public/cosmetics/redrawn/<piece>.webp). */\n` +
  `export const REDRAWN_PIECES: readonly string[] = ${JSON.stringify(images)};\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    console.error(`cosmetic-redraws: ${OUT} is not what the sources build: run bun scripts/cosmetic-redraws.ts`);
    process.exit(1);
  }
  console.log("cosmetic-redraws: up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`cosmetic-redraws: ${Object.keys(card.cardArts).length} card arts, ${Object.keys(card.frames).length} frames, ${Object.keys(card.names).length} name colours, ${Object.keys(cos.finishes).length} finishes, ${Object.keys(cos.reactions).length} reaction packs, ${Object.keys(cos.celebrations).length} celebrations, ${Object.keys(cos.tiles).length} tile styles, ${images.length} pieces → ${OUT}`);
}
