/**
 * Profile's art (phase 2 step 3, 14 Nov 2026): the style guide's 3D art-kit icons
 * (docs/design/style-guide/art/*.png, 192 px renders) cut to the sizes Profile's rating tiles and Mastery draw, at 1x, 2x and 3x, as
 * WebP in public/profile-art/, plus src/components/profile/profileArt.data.ts (each image's url with its content hash, its size and
 * the alt text). Never upscaled: a 3x past the 192 px source is left out (the browser takes the 2x).
 *
 *   bun scripts/profile-art.ts          rebuild
 *   bun scripts/profile-art.ts --check  rebuild in memory and fail if anything on disk differs (profile-art-check)
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/profile-art");
const DATA = join(ROOT, "src/components/profile/profileArt.data.ts");

/** Every image Profile draws: its art-kit source, the CSS px it is drawn at, and what it shows. */
export const PROFILE_ART = {
  rating: { src: "joules", px: 44, alt: "Joulz Rating" },
  puzzles: { src: "puzzles", px: 44, alt: "Puzzles" },
  arcade: { src: "arcade", px: 44, alt: "Arcade" },
  gem: { src: "gem", px: 40, alt: "Gem" },
} as const;

export type ProfileArtName = keyof typeof PROFILE_ART;

async function build(): Promise<{ files: Map<string, Buffer>; data: string }> {
  const files = new Map<string, Buffer>();
  const entries: string[] = [];
  for (const [name, spec] of Object.entries(PROFILE_ART)) {
    const image = await loadImage(readFileSync(join(SOURCE, `${spec.src}.png`)));
    const urls: string[] = [];
    for (const scale of [1, 2, 3]) {
      const size = spec.px * scale;
      if (size > image.width) continue;
      const canvas = createCanvas(size, size);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, size, size);
      const bytes = Buffer.from(await canvas.encode("webp", 88));
      const file = `${name}-${scale}x.webp`;
      files.set(file, bytes);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      urls.push(`"/profile-art/${file}?v=${hash}"`);
    }
    entries.push(`  ${name}: { px: ${spec.px}, alt: ${JSON.stringify(spec.alt)}, urls: [${urls.join(", ")}] },`);
  }
  const data = `// Generated by scripts/profile-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x, 2x and (where the 192 px source allows) 3x WebP.\nexport const PROFILE_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type ProfileArtName = keyof typeof PROFILE_ART;\n`;
  return { files, data };
}

const check = process.argv.includes("--check");
const { files, data } = await build();
let total = 0;
for (const b of files.values()) total += b.length;
if (check) {
  const problems: string[] = [];
  for (const [file, bytes] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) problems.push(`public/profile-art/${file} differs`);
  }
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("profileArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/profile-art.ts)`);
    process.exit(1);
  }
  console.log(`profile art matches: ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
}
