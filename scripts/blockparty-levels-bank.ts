/**
 * Builds Tessellate's level banks (the Pattern overhaul, stage 3, 16 Nov 2026; src/lib/levels/pattern/blockparty.levels.ts)
 * in src/lib/duel/blockPartyLevelBank.server.ts: Easy, Hard and Expert, BLOCK_LEVEL_BANK_SIZE boards each. Entry i of a
 * level is generateBlockLevel(level, 60) under the fixed seed hash("blockLevel", level, i, retry), the first retry that
 * gives a new board, so each bank rebuilds byte for byte. Every board's solution count is counted exhaustively and lies
 * in its level's band; Expert's are each finished by the human-like solver. Runs on four worker processes.
 *
 *   bun scripts/blockparty-levels-bank.ts            # build and write
 *   bun scripts/blockparty-levels-bank.ts --check    # rebuild and compare, no write
 */
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { BLOCK_LEVELS, generateBlockLevel, type BlockLevel } from "../src/lib/duel/blockPartyLevels.server";
import { withSeededRandom } from "../src/lib/duel/random";
import type { BlockPartyPuzzleData } from "../src/lib/duel/types";

export const BLOCK_LEVEL_BANK_SIZE = 300;
const OUT = "src/lib/duel/blockPartyLevelBank.server.ts";

export function blockLevelSeed(level: BlockLevel, index: number, retry: number): number {
  let h = 2166136261;
  for (const ch of `blockLevel:${level}:${index}:${retry}`) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return h >>> 0;
}

/** Entry `index` of a level at `retry` (null when that seed finds no board in its attempts). */
export function blockLevelCandidate(level: BlockLevel, index: number, retry: number): BlockPartyPuzzleData | null {
  return withSeededRandom(blockLevelSeed(level, index, retry), () => generateBlockLevel(level, 60));
}

function firstCandidate(level: BlockLevel, index: number, from = 0): { retry: number; puzzle: BlockPartyPuzzleData } {
  for (let retry = from; ; retry++) {
    const puzzle = blockLevelCandidate(level, index, retry);
    if (puzzle) return { retry, puzzle };
  }
}

interface Found {
  level: BlockLevel;
  index: number;
  retry: number;
  puzzle: BlockPartyPuzzleData;
}

const args = process.argv.slice(2);
if (args[0] === "--worker") {
  const [k, n] = [Number(args[1]), Number(args[2])];
  let job = 0;
  for (const level of BLOCK_LEVELS)
    for (let i = 0; i < BLOCK_LEVEL_BANK_SIZE; i++, job++)
      if (job % n === k) console.log(JSON.stringify({ level, index: i, ...firstCandidate(level, i) }));
  process.exit(0);
}

if (import.meta.main) {
  const n = Number(process.env["BANK_WORKERS"] ?? 4);
  const found: Found[] = [];
  await Promise.all(
    Array.from({ length: n }, (_, k) =>
      new Promise<void>((resolve, reject) => {
        const child = spawn("bun", [import.meta.path, "--worker", String(k), String(n)], { stdio: ["ignore", "pipe", "inherit"] });
        let buf = "";
        child.stdout.setEncoding("utf8");
        child.stdout.on("data", (chunk: string) => {
          buf += chunk;
          let nl: number;
          while ((nl = buf.indexOf("\n")) >= 0) {
            const line = buf.slice(0, nl);
            buf = buf.slice(nl + 1);
            if (line.trim()) {
              found.push(JSON.parse(line));
              if (found.length % 100 === 0) console.error(`${found.length}/${BLOCK_LEVEL_BANK_SIZE * BLOCK_LEVELS.length}`);
            }
          }
        });
        child.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`worker ${k} exited ${code}`))));
      }),
    ),
  );
  const banks = {} as Record<BlockLevel, Found[]>;
  for (const level of BLOCK_LEVELS) {
    const list = found.filter((f) => f.level === level).sort((a, b) => a.index - b.index);
    // A duplicate board moves the later index on to its next retry.
    const seen = new Set<string>();
    for (const entry of list) {
      let e = entry;
      while (seen.has(e.puzzle.blockers.join(","))) e = { ...e, ...firstCandidate(level, e.index, e.retry + 1) };
      seen.add(e.puzzle.blockers.join(","));
      Object.assign(entry, e);
    }
    banks[level] = list;
  }
  const source = `/* Generated by scripts/blockparty-levels-bank.ts — do not edit by hand. Rebuild with \`bun scripts/blockparty-levels-bank.ts\`. */
import type { BlockPartyPuzzleData } from "./types";

/**
 * Tessellate's level boards (the Pattern overhaul, stage 3; src/lib/levels/pattern/blockparty.levels.ts), ${BLOCK_LEVEL_BANK_SIZE} a level.
 * Every board's solution count is counted exhaustively and lies in its level's band (\`solutions\`); Expert's are each
 * finished by the human-like solver (blockPartyLevels.server.ts humanSolveBlock).
 */
export const BLOCK_LEVEL_RETRIES: Record<"easy" | "hard" | "expert", number[]> = {
${BLOCK_LEVELS.map((l) => `  ${l}: [${banks[l].map((e) => e.retry).join(",")}],`).join("\n")}
};

export const BLOCK_LEVEL_BANK: Record<"easy" | "hard" | "expert", BlockPartyPuzzleData[]> = {
${BLOCK_LEVELS.map((l) => `  ${l}: [\n${banks[l].map((e) => `    ${JSON.stringify(e.puzzle)},`).join("\n")}\n  ],`).join("\n")}
};
`;
  if (args.includes("--check")) {
    const { readFileSync } = await import("node:fs");
    const same = readFileSync(OUT, "utf8") === source;
    console.log(same ? "blockparty level banks rebuild identically" : "FAIL: blockparty level banks differ");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, source);
  console.log(BLOCK_LEVELS.map((l) => `${l} ${banks[l].length}`).join(", "), "boards written");
}
