/**
 * Writes src/lib/duel/revealPalette.data.ts (3 Nov 2026): each game's answer-reveal gradient, taken from its tile
 * image (public/tiles/<type>.webp, made by `bun scripts/shots/tile-scenes.ts` from the game's own art).
 *
 *   bun scripts/reveal-palette.ts          write the file
 *   bun scripts/reveal-palette.ts --check  exit 1 if the file differs from what the tiles give (reveal-palette-check runs this)
 *
 * The colours: the tile's pixels are binned by hue, weighted by saturation and brightness; the strongest hue's mean
 * colour is the top stop, the strongest hue at least 50° from it (if it carries a fifth of the weight) the middle
 * stop, else the top's own colour; the bottom is the top stop at 40 %. Every stop is darkened (keeping its hue)
 * until white text on it reads at least REVEAL_MIN_CONTRAST:1, so the gradient is the game's colour, dark.
 * A tile with no saturated colour (a black-and-white game) gets the app's neutral gradient. Deterministic: the
 * same tiles give the same file.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createCanvas, loadImage } from "@napi-rs/canvas";

import { TILE_SCENES } from "../src/components/app/gameIcons/tileScenes.data";
import { REVEAL_FALLBACK, REVEAL_MIN_CONTRAST, rgbToHex, whiteContrast } from "../src/lib/duel/revealPalette";

const OUT = "src/lib/duel/revealPalette.data.ts";
const SIZE = 64;

type Rgb = [number, number, number];

function hsv([r, g, b]: Rgb): [number, number, number] {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const d = max - min;
  let h = 0;
  if (d > 0) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  return [h, max === 0 ? 0 : d / max, max / 255];
}

/** Scales a colour towards black (its hue and saturation kept) until white on it reads `contrast`:1. */
function darkenTo(rgb: Rgb, contrast: number): Rgb {
  let k = 1;
  let out = rgb;
  while (whiteContrast(out) < contrast && k > 0.02) {
    k -= 0.01;
    out = [rgb[0] * k, rgb[1] * k, rgb[2] * k];
  }
  return out.map((v) => Math.round(v)) as Rgb;
}

const hueGap = (a: number, b: number) => Math.min(Math.abs(a - b), 360 - Math.abs(a - b));

async function paletteOf(path: string): Promise<[string, string, string]> {
  const img = await loadImage(readFileSync(path));
  const canvas = createCanvas(SIZE, SIZE);
  const ctx = canvas.getContext("2d");
  ctx.drawImage(img, 0, 0, SIZE, SIZE);
  const data = ctx.getImageData(0, 0, SIZE, SIZE).data;
  const BINS = 24;
  const bins = Array.from({ length: BINS }, () => ({ w: 0, r: 0, g: 0, b: 0, h: 0 }));
  let total = 0;
  for (let i = 0; i < data.length; i += 4) {
    const rgb: Rgb = [data[i]!, data[i + 1]!, data[i + 2]!];
    const [h, s, v] = hsv(rgb);
    if (s < 0.25 || v < 0.12) continue;
    const w = s * v;
    const bin = bins[Math.floor(h / (360 / BINS)) % BINS]!;
    bin.w += w;
    bin.r += rgb[0] * w;
    bin.g += rgb[1] * w;
    bin.b += rgb[2] * w;
    bin.h += h * w;
    total += w;
  }
  // Too little colour: the neutral gradient.
  if (total < SIZE * SIZE * 0.02) return [...REVEAL_FALLBACK];
  const ranked = bins
    .map((b) => ({ w: b.w, rgb: [b.r / (b.w || 1), b.g / (b.w || 1), b.b / (b.w || 1)] as Rgb, h: b.h / (b.w || 1) }))
    .filter((b) => b.w > 0)
    .sort((a, b) => b.w - a.w);
  const first = ranked[0]!;
  const second = ranked.find((b) => hueGap(b.h, first.h) >= 50 && b.w >= first.w * 0.2);
  const top = darkenTo(first.rgb, REVEAL_MIN_CONTRAST + 1);
  const mid = darkenTo(second ? second.rgb : first.rgb, REVEAL_MIN_CONTRAST + 4);
  // The bottom: the top stop at 40 % (always darker than it, whatever the tile).
  const bottom = top.map((v) => Math.round(v * 0.4)) as Rgb;
  return [rgbToHex(top), rgbToHex(mid), rgbToHex(bottom)];
}

const entries: [string, [string, string, string]][] = [];
for (const type of Object.keys(TILE_SCENES).sort()) {
  const path = `public/tiles/${type}.webp`;
  if (!existsSync(path)) continue;
  entries.push([type, await paletteOf(path)]);
}

const text = `/**
 * Generated by \`bun scripts/reveal-palette.ts\` from the tile images (public/tiles); do not edit. Each game's answer
 * reveal gradient [top, middle, bottom] (revealPalette.ts): the tile's strongest colours, darkened so white text reads
 * at least ${REVEAL_MIN_CONTRAST}:1 on every stop. Re-run after re-exporting tiles (reveal-palette-check fails until then).
 */
export const REVEAL_PALETTE: Readonly<Record<string, readonly [string, string, string]>> = {
${entries.map(([t, [a, b, c]]) => `  ${/^[a-z][a-z0-9]*$/i.test(t) ? t : JSON.stringify(t)}: ["${a}", "${b}", "${c}"],`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== text) {
    console.log(`FAIL ${OUT} is out of date: run bun scripts/reveal-palette.ts`);
    process.exit(1);
  }
  console.log(`PASS ${OUT} matches the tiles (${entries.length} games)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}: ${entries.length} games`);
}
