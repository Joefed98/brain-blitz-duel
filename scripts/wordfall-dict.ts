/**
 * Builds Letterfall's phone dictionary (src/lib/arcade/wordfallWords.data.ts)
 * from the one server dictionary: the SCOWL British list behind
 * dictionary.server.ts, 3-12 letters, minus every blocked word, minus words
 * with a Q not followed by U (Letterfall's only Q tile is "Qu", so no chain can
 * spell them). Sorted and front-coded: each word is one character giving how
 * many letters it shares with the word before ('0' + n), then the rest of it.
 * Exact, not probabilistic; the phone decodes it into a Set.
 *
 * Writes three files from the one list: the server/check module
 * (wordfallWords.data.ts), the tiny version module the main bundle carries
 * (wordfallWords.meta.ts: count, hash and the phone's URL), and the phone's
 * copy, public/wordfall/words-<hash>.txt (fetched, so a failed download can be
 * retried, and cached on the device). Older public versions are removed.
 *
 *   bun scripts/wordfall-dict.ts           # rewrite the data file
 *   bun scripts/wordfall-dict.ts --check   # prove the committed file is current
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

import { isBlockedWord } from "../src/lib/duel/dictionary.server";
import { SCOWL_WORDS_RAW } from "../src/lib/duel/wordlist.server";
import {
  encodeWordfallWords,
  WORDFALL_DATA_PATH,
  WORDFALL_META_PATH,
  WORDFALL_PUBLIC_DIR,
  wordfallPublicName,
  wordfallWordsHash,
} from "./wordfall-lib";

/** Every word Letterfall accepts, sorted. */
export function wordfallSourceWords(): string[] {
  const words = new Set<string>();
  for (const word of SCOWL_WORDS_RAW.split(/\s+/)) {
    if (!/^[a-z]{3,12}$/.test(word) || isBlockedWord(word) || /q(?!u)/.test(word)) continue;
    words.add(word);
  }
  return [...words].sort();
}

export function wordfallDataSource(): string {
  const words = wordfallSourceWords();
  const packed = encodeWordfallWords(words);
  return `/**
 * Letterfall's word list: generated by scripts/wordfall-dict.ts from the SCOWL
 * British list behind dictionary.server.ts (3-12 letters, blocked words removed,
 * no Q without U). Front-coded: '0' + n shared letters, then the rest. Exact.
 * The server and checks install this copy; the phone fetches the identical
 * public/wordfall/words-<hash>.txt (see wordfallWords.meta.ts). Never edit by hand.
 */
export const WORDFALL_WORD_COUNT = ${words.length};
export const WORDFALL_WORDS_HASH = ${wordfallWordsHash(words)};
export const WORDFALL_WORDS_FC = ${JSON.stringify(packed)};
`;
}

/** The tiny always-bundled module naming the list's version (count and hash), for the phone cache key. */
export function wordfallMetaSource(): string {
  const words = wordfallSourceWords();
  return `/** Letterfall word-list version, generated by scripts/wordfall-dict.ts with wordfallWords.data.ts. Tiny, so it ships in the main bundle as the phone cache key. */
export const WORDFALL_META = {
  count: ${words.length},
  hash: ${wordfallWordsHash(words)},
  /** The phone's copy of the packed list (public/), one URL per version. */
  url: "/wordfall/${wordfallPublicName(wordfallWordsHash(words))}",
} as const;
`;
}

/** The phone's text file: exactly the packed string the server module holds. */
export function wordfallPublicFile(): { path: string; source: string } {
  const words = wordfallSourceWords();
  return { path: WORDFALL_PUBLIC_DIR + wordfallPublicName(wordfallWordsHash(words)), source: encodeWordfallWords(words) };
}

if (import.meta.main) {
  const pub = wordfallPublicFile();
  const files: [string, string][] = [[WORDFALL_DATA_PATH, wordfallDataSource()], [WORDFALL_META_PATH, wordfallMetaSource()], [pub.path, pub.source]];
  if (process.argv.includes("--check")) {
    for (const [path, source] of files) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== source) {
        console.log(`FAIL: ${path} is out of date; run bun scripts/wordfall-dict.ts`);
        process.exit(1);
      }
    }
    console.log("wordfall dictionary data is current");
  } else {
    mkdirSync(WORDFALL_PUBLIC_DIR, { recursive: true });
    for (const name of readdirSync(WORDFALL_PUBLIC_DIR)) if (WORDFALL_PUBLIC_DIR + name !== pub.path) rmSync(WORDFALL_PUBLIC_DIR + name);
    for (const [path, source] of files) {
      writeFileSync(path, source);
      console.log(`wrote ${path} (${source.length} bytes)`);
    }
  }
}
