/**
 * Lightbender's level banks (16 Nov 2026; src/lib/duel/laserLevels.server.ts).
 *
 *   bun scripts/laser-bank.ts --level=hard|expert|all [--check] [--count=N]
 *
 * Entry i is the level's generator under laserLevelSeed(level, i, retry) for the smallest retry whose board is not
 * already in the bank; each board passes the generator's proofs and the person-like solver's floor and ceiling as it is
 * built. Writes src/lib/duel/laser<Level>Bank.server.ts; --check rebuilds and compares byte for byte without writing.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

import { LASER_BANK_SIZE, buildLaserLevelEntry, laserLevelKey, laserLevelSeed, type LaserBankLevel } from "../src/lib/duel/laserLevels.server";
import type { LaserPuzzleData } from "../src/lib/duel/types";

const MAX_RETRIES = 20;

export function buildLaserBank(level: LaserBankLevel, count = LASER_BANK_SIZE[level]): { source: string; entries: number } {
  const entries: LaserPuzzleData[] = [];
  const retries: number[] = [];
  const keys = new Set<string>();
  for (let index = 0; index < count; index++) {
    let found = false;
    for (let retry = 0; retry < MAX_RETRIES && !found; retry++) {
      // A seed whose search builds no layout is passed over like a duplicate (D4, 22 Nov 2026: Expert's exact tray of
      // 10–12 mirrors and 9–10 bombs leaves a few seeds without one).
      let puzzle: LaserPuzzleData;
      try {
        puzzle = buildLaserLevelEntry(level, laserLevelSeed(level, index, retry));
      } catch {
        continue;
      }
      const key = laserLevelKey(puzzle);
      if (keys.has(key)) continue;
      keys.add(key);
      entries.push(puzzle);
      retries.push(retry);
      found = true;
    }
    if (!found) throw new Error(`laser ${level} bank entry ${index}: no new board in ${MAX_RETRIES} seeds`);
    if ((index + 1) % 50 === 0) console.error(`[laser ${level}] ${index + 1}/${count}`);
  }
  const U = level.toUpperCase();
  const sha = createHash("sha256").update(JSON.stringify(entries)).digest("hex");
  const source = `/* Generated by scripts/laser-bank.ts --level=${level}; do not edit by hand. Rebuild with \`bun scripts/laser-bank.ts --level=${level}\`. */
import type { LaserPuzzleData } from "./types";

/** Build facts: entry i is generateLaserLevel(${level}) under laserLevelSeed("${level}", i, LASER_${U}_BANK_RETRIES[i]) (laserLevels.server.ts). */
export const LASER_${U}_BANK_BUILD = { entries: ${entries.length}, sha256: "${sha}" } as const;

export const LASER_${U}_BANK_RETRIES: number[] = [${retries.join(",")}];

export const LASER_${U}_BANK: LaserPuzzleData[] = [
${entries.map((e) => `  ${JSON.stringify(e)},`).join("\n")}
];
`;
  return { source, entries: entries.length };
}

export const laserBankPath = (level: LaserBankLevel) =>
  new URL(`../src/lib/duel/laser${level[0]!.toUpperCase()}${level.slice(1)}Bank.server.ts`, import.meta.url);

if (import.meta.main) {
  const args = process.argv.slice(2);
  const levelArg = args.find((a) => a.startsWith("--level="))?.slice("--level=".length) ?? "all";
  const count = Number(args.find((a) => a.startsWith("--count="))?.slice("--count=".length) ?? 0) || undefined;
  const check = args.includes("--check");
  const levels: LaserBankLevel[] = levelArg === "all" ? ["hard", "expert"] : [levelArg as LaserBankLevel];
  let bad = 0;
  for (const level of levels) {
    if (level !== "hard" && level !== "expert") throw new Error(`unknown level ${level}`);
    const t0 = Date.now();
    const built = buildLaserBank(level, count);
    const seconds = ((Date.now() - t0) / 1000).toFixed(0);
    if (check) {
      const same = readFileSync(laserBankPath(level), "utf8") === built.source;
      if (!same) bad++;
      console.log(`${same ? "PASS" : "FAIL"} laser ${level}: rebuild of ${built.entries} entries ${same ? "matches" : "differs from"} the committed bank (${seconds} s)`);
    } else {
      writeFileSync(laserBankPath(level), built.source);
      console.log(`laser ${level}: wrote ${built.entries} entries, ${(Buffer.byteLength(built.source) / 1024).toFixed(0)} KB (${seconds} s)`);
    }
  }
  if (bad) process.exit(1);
}
