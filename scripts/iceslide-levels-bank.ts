/**
 * Builds Skid's level banks (difficulty levels, 16 Nov 2026) in src/lib/duel/iceSlideLevelBank.server.ts: Easy, Hard
 * and Expert, each `settings.bank` boards (src/lib/levels/pattern/iceslide.levels.ts).
 *
 *   bun scripts/iceslide-levels-bank.ts            rebuild and write the banks
 *   bun scripts/iceslide-levels-bank.ts --check    rebuild in memory; fail unless it matches the committed file byte for byte
 *   bun scripts/iceslide-levels-bank.ts --jobs=2   worker processes (default: CPU count)
 *
 * Determinism (as scripts/puzzle-bank-lib.ts): entry i of a level is the level generator under the fixed seed
 * `iceSlideLevelEntrySeed(level, i, retry)` for the smallest retry whose board passes `verifyIceSlideLevelPuzzle` (a
 * fresh breadth-first search proves the stored minimum is the board's fewest slides, in the level's band, and the
 * stored route reaches the exit in it) and isn't a copy of an earlier entry. Workers only compute candidates; the parent
 * merges them in index order, so no clock, CSPRNG or scheduling reaches the result.
 */
import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { cpus } from "node:os";
import { fileURLToPath } from "node:url";

import {
  ICESLIDE_BANK_LEVELS,
  buildIceSlideLevelEntry,
  iceSlideLevelKey,
  iceSlideLevelSettings,
  type IceSlideLevel,
} from "../src/lib/duel/iceSlideLevels.server";
import type { SlidePuzzleData } from "../src/lib/duel/types";
import { SKID_ELITE_PERSON, playSkidLikeAPerson } from "./iceslide-human";

const MAX_RETRIES = 256;
export const ICESLIDE_LEVEL_BANK_PATH = fileURLToPath(new URL("../src/lib/duel/iceSlideLevelBank.server.ts", import.meta.url));

interface Candidate {
  index: number;
  retry: number;
  puzzle: SlidePuzzleData;
}

/**
 * A level that keeps only boards a person can finish (D4, 22 Nov 2026: Expert): the elite person-like player
 * (scripts/iceslide-human.ts, its own times, every one at or over the human limits) must reach the exit inside the
 * level's clock.
 */
function personFinishes(level: IceSlideLevel, puzzle: SlidePuzzleData): boolean {
  const s = iceSlideLevelSettings(level) as { personSolvable?: boolean; timeLimitMs: number };
  if (!s.personSolvable) return true;
  return playSkidLikeAPerson(puzzle as never, SKID_ELITE_PERSON, s.timeLimitMs).solved;
}

function candidateFor(level: IceSlideLevel, index: number, fromRetry = 0): Candidate {
  for (let retry = fromRetry; retry < MAX_RETRIES; retry++) {
    const puzzle = buildIceSlideLevelEntry(level, index, retry);
    if (puzzle && personFinishes(level, puzzle)) return { index, retry, puzzle };
  }
  throw new Error(`iceslide ${level} bank entry ${index}: no verified board in ${MAX_RETRIES} fixed seeds`);
}

async function candidates(level: IceSlideLevel, count: number, jobs: number): Promise<Candidate[]> {
  const out: Candidate[] = new Array(count);
  const self = fileURLToPath(import.meta.url);
  await Promise.all(
    Array.from({ length: jobs }, (_, worker) =>
      new Promise<void>((resolve, reject) => {
        const child = spawn(process.execPath, [self, "--worker", level, String(count), String(worker), String(jobs)], { stdio: ["ignore", "pipe", "inherit"] });
        let buffer = "";
        child.stdout.setEncoding("utf8");
        child.stdout.on("data", (chunk: string) => {
          buffer += chunk;
          let nl: number;
          while ((nl = buffer.indexOf("\n")) >= 0) {
            const line = buffer.slice(0, nl);
            buffer = buffer.slice(nl + 1);
            if (line.trim()) {
              const c = JSON.parse(line) as Candidate;
              out[c.index] = c;
            }
          }
        });
        child.on("error", reject);
        child.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`${level} worker ${worker} exited ${code}`))));
      }),
    ),
  );
  for (let i = 0; i < count; i++) if (!out[i]) throw new Error(`${level} entry ${i} missing`);
  return out;
}

function merge(level: IceSlideLevel, list: Candidate[]): { entries: SlidePuzzleData[]; retries: number[] } {
  const seen = new Set<string>();
  const entries: SlidePuzzleData[] = [];
  const retries: number[] = [];
  for (const first of list) {
    let c = first;
    while (seen.has(iceSlideLevelKey(c.puzzle))) c = candidateFor(level, c.index, c.retry + 1);
    seen.add(iceSlideLevelKey(c.puzzle));
    entries.push(c.puzzle);
    retries.push(c.retry);
  }
  return { entries, retries };
}

export function levelEntriesHash(entries: readonly SlidePuzzleData[]): string {
  return createHash("sha256").update(JSON.stringify(entries)).digest("hex");
}

function render(built: Record<IceSlideLevel, { entries: SlidePuzzleData[]; retries: number[] }>): string {
  const lv = ICESLIDE_BANK_LEVELS;
  return `/* Generated by scripts/iceslide-levels-bank.ts — do not edit by hand. Rebuild with \`bun scripts/iceslide-levels-bank.ts\`. */
import type { SlidePuzzleData } from "./types";

/** Build facts: entry i of a level is generateIceSlideLevel under iceSlideLevelEntrySeed(level, i, ICESLIDE_LEVEL_BANK_RETRIES[level][i]). */
export const ICESLIDE_LEVEL_BANK_BUILD = {
${lv.map((l) => `  ${l}: { entries: ${built[l].entries.length}, sha256: "${levelEntriesHash(built[l].entries)}" },`).join("\n")}
} as const;

export const ICESLIDE_LEVEL_BANK_RETRIES: Record<"easy" | "hard" | "expert", number[]> = {
${lv.map((l) => `  ${l}: ${JSON.stringify(built[l].retries)},`).join("\n")}
};

export const ICESLIDE_LEVEL_BANKS: Record<"easy" | "hard" | "expert", SlidePuzzleData[]> = {
${lv.map((l) => `  ${l}: [\n${built[l].entries.map((e) => `    ${JSON.stringify(e)},`).join("\n")}\n  ],`).join("\n")}
};
`;
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const jobs = Math.max(1, Number(args.find((a) => a.startsWith("--jobs="))?.split("=")[1] ?? cpus().length));
  const check = args.includes("--check");
  const built = {} as Record<IceSlideLevel, { entries: SlidePuzzleData[]; retries: number[] }>;
  for (const level of ICESLIDE_BANK_LEVELS) {
    const t0 = Date.now();
    const count = iceSlideLevelSettings(level).bank;
    built[level] = merge(level, await candidates(level, count, Math.min(jobs, count)));
    const mins = built[level].entries.map((e) => e.minMoves ?? 0);
    console.log(`iceslide ${level}: ${count} boards, minimum ${Math.min(...mins)}–${Math.max(...mins)}, ${built[level].retries.filter((r) => r > 0).length} needed a retry, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  }
  const source = render(built);
  if (check) {
    const same = readFileSync(ICESLIDE_LEVEL_BANK_PATH, "utf8") === source;
    console.log(same ? "PASS iceslide level banks: rebuild matches iceSlideLevelBank.server.ts" : "FAIL iceslide level banks: rebuild differs from iceSlideLevelBank.server.ts");
    if (!same) process.exit(1);
    return;
  }
  writeFileSync(ICESLIDE_LEVEL_BANK_PATH, source);
  console.log(`wrote ${ICESLIDE_LEVEL_BANK_PATH} (${(Buffer.byteLength(source) / 1024).toFixed(0)} KB)`);
}

if (process.argv[2] === "--worker") {
  const [, , , level, count, worker, jobs] = process.argv;
  for (let index = Number(worker); index < Number(count); index += Number(jobs)) {
    process.stdout.write(`${JSON.stringify(candidateFor(level as IceSlideLevel, index))}\n`);
  }
} else if (import.meta.main) {
  await main();
}
