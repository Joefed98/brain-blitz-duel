/**
 * Builds a server-only bank of proved swingRev 4 Grappler courses in
 * src/lib/duel/swingBankV4.server.ts, the same way Bomb Defusal uses
 * scripts/bomb-bank.ts.
 *
 * Each course is just a seed (the whole cavern, anchors, spikes, star anchors,
 * stalactites and lava jets are deterministically rebuilt from it) plus the tick
 * and star count of its reference beam search (proveSwingSeedV4), recorded here as
 * the proof result. A course is banked only when the search reaches 500 m having
 * taken every star, so every banked course can score 150 against the chasing
 * dragon. Proving takes seconds a course, so it runs here, not while a room starts.
 *
 *   bun scripts/swing-bank.ts 300                 # build and write
 *   bun scripts/swing-bank.ts 60 /tmp/a.json       # one shard (merge with --merge)
 *   bun scripts/swing-bank.ts --merge /tmp/a.json /tmp/b.json ...
 *
 * Taller worlds batch 3 (swingRev 9): --tall re-proves every SWING_V4_BANK
 * course on the taller cavern (the same search on swingRev 9, its witness
 * replayed on the real sim to 500 m with all ten stars and 150) and writes the
 * ones that pass, in bank order, to src/lib/duel/swingBankV9.server.ts, which
 * rooms deal swingRev 9 from:
 *
 *   bun scripts/swing-bank.ts --tall                          # all of it
 *   bun scripts/swing-bank.ts --tall --part=1/4 /tmp/t1.json   # one shard
 *   bun scripts/swing-bank.ts --tall --merge /tmp/t1.json ...
 *
 * The expansion (swingRev 13): --expand re-proves every SWING_V9_BANK course on the expansion's deeper
 * cavern. A course is kept when its start state carries every feature (two or three full set-route sections,
 * SWING_GEMS gems, SWING_GATES gates, ten stars) and the same reference search reaches 500 m with
 * every star, its witness replayed on the real sim (score at least 150); written in bank order to
 * src/lib/duel/swingBankV13.server.ts, which rooms deal swingRev 13 from:
 *
 *   bun scripts/swing-bank.ts --expand                            # all of it
 *   bun scripts/swing-bank.ts --expand --part=1/4 /tmp/x1.json    # one shard
 *   bun scripts/swing-bank.ts --expand --merge /tmp/x1.json ...
 */
import { readFileSync, writeFileSync } from "node:fs";
import { arcadeSeed } from "../src/lib/duel/arcade.server";
import { proveSwingSeedV4, swingExpandComplete } from "../src/lib/duel/swingProof.server";
import { swingGameFor, SWING_REV, SWING_REV_EXPAND, SWING_REV_TALL, SWING_STARS } from "../src/lib/arcade/swing";
import { SWING_V9_BANK } from "../src/lib/duel/swingBankV9.server";
import { SWING_V4_BANK, type SwingBankEntry } from "../src/lib/duel/swingBankV4.server";

const OUT = "src/lib/duel/swingBankV4.server.ts";

function write(entries: SwingBankEntry[]) {
  const unique = new Map(entries.map((entry) => [entry.seed, entry]));
  writeFileSync(
    OUT,
    `/* Generated by scripts/swing-bank.ts — do not edit by hand. */\nexport interface SwingBankEntry {\n  seed: number;\n  /** Proof-witness completion tick and stars taken (all of them), recorded at build time (not replayed from). */\n  ticks: number;\n  stars: number;\n}\n\n/** swingRev 4 courses whose reference search reaches 500 m with every star. */\nexport const SWING_V4_BANK: SwingBankEntry[] = ${JSON.stringify([...unique.values()])};\n`,
  );
  console.log(`wrote ${unique.size} courses to ${OUT}`);
}

/** One bank course re-proved on swingRev 9 (null when the search or its replay falls short). */
function proveTall(seed: number): SwingBankEntry | null {
  const game = swingGameFor(SWING_REV_TALL);
  if ((game.init(seed).starSpots ?? []).length !== SWING_STARS) return null;
  const witness = proveSwingSeedV4(seed, { rev: SWING_REV_TALL });
  if (!witness || witness.stars !== SWING_STARS) return null;
  let s = game.init(seed);
  const events = new Map(witness.log.map((e) => [e.t, e]));
  while (!s.ended) s = game.step(s, events.get(s.tick + 1) ?? null);
  if (s.ended !== 1 || (s.stars ?? 0) !== SWING_STARS || game.score(s) !== 150) return null;
  return { seed, ticks: s.tick, stars: s.stars ?? 0 };
}

function writeTall(entries: SwingBankEntry[]) {
  const order = new Map(SWING_V4_BANK.map((e, i) => [e.seed, i]));
  const sorted = [...new Map(entries.map((e) => [e.seed, e])).values()].sort((a, b) => order.get(a.seed)! - order.get(b.seed)!);
  writeFileSync(
    TALL_OUT,
    `/* Generated by scripts/swing-bank.ts --tall — do not edit by hand. */\nimport type { SwingBankEntry } from "./swingBankV4.server";\n\n/** swingRev 9 (taller cavern): the SWING_V4_BANK courses whose reference search on the taller cavern still reaches 500 m with every star. */\nexport const SWING_V9_BANK: SwingBankEntry[] = ${JSON.stringify(sorted)};\n`,
  );
  console.log(`wrote ${sorted.length} of ${SWING_V4_BANK.length} courses to ${TALL_OUT}`);
}

const TALL_OUT = "src/lib/duel/swingBankV9.server.ts";
const EXPAND_OUT = "src/lib/duel/swingBankV13.server.ts";

/** One bank course re-proved on swingRev 13 (null when a feature is missing, or the search or its replay falls short). */
function proveExpand(seed: number): SwingBankEntry | null {
  if (!swingExpandComplete(seed)) return null;
  const game = swingGameFor(SWING_REV_EXPAND);
  const witness = proveSwingSeedV4(seed, { rev: SWING_REV_EXPAND });
  if (!witness || witness.stars !== SWING_STARS) return null;
  let s = game.init(seed);
  const events = new Map(witness.log.map((e) => [e.t, e]));
  while (!s.ended) s = game.step(s, events.get(s.tick + 1) ?? null);
  if (s.ended !== 1 || (s.stars ?? 0) !== SWING_STARS || game.score(s) < 150) return null;
  return { seed, ticks: s.tick, stars: s.stars ?? 0 };
}

function writeExpand(entries: SwingBankEntry[]) {
  const order = new Map(SWING_V9_BANK.map((e, i) => [e.seed, i]));
  const sorted = [...new Map(entries.map((e) => [e.seed, e])).values()].sort((a, b) => order.get(a.seed)! - order.get(b.seed)!);
  writeFileSync(
    EXPAND_OUT,
    `/* Generated by scripts/swing-bank.ts --expand — do not edit by hand. */\nimport type { SwingBankEntry } from "./swingBankV4.server";\n\n/** swingRev 13 (the expansion): the SWING_V9_BANK courses with every expansion feature whose reference search still reaches 500 m with every star. */\nexport const SWING_V13_BANK: SwingBankEntry[] = ${JSON.stringify(sorted)};\n`,
  );
  console.log(`wrote ${sorted.length} of ${SWING_V9_BANK.length} courses to ${EXPAND_OUT}`);
}

if (process.argv[2] === "--expand") {
  const rest = process.argv.slice(3);
  if (rest[0] === "--merge") writeExpand(rest.slice(1).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as SwingBankEntry[]));
  else {
    const part = rest.find((a) => a.startsWith("--part="))?.slice(7).split("/").map(Number) ?? [1, 1];
    const out: SwingBankEntry[] = [];
    const started = Date.now();
    SWING_V9_BANK.forEach((entry, i) => {
      if (i % part[1]! !== part[0]! - 1) return;
      const proved = proveExpand(entry.seed);
      if (proved) out.push(proved);
    });
    console.log(`part ${part.join("/")}: ${out.length} proved in ${((Date.now() - started) / 1000).toFixed(0)} s`);
    const file = rest.find((a) => !a.startsWith("--"));
    if (file) writeFileSync(file, JSON.stringify(out));
    else writeExpand(out);
  }
} else if (process.argv[2] === "--tall") {
  const rest = process.argv.slice(3);
  if (rest[0] === "--merge") writeTall(rest.slice(1).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as SwingBankEntry[]));
  else {
    const part = rest.find((a) => a.startsWith("--part="))?.slice(7).split("/").map(Number) ?? [1, 1];
    const out: SwingBankEntry[] = [];
    const started = Date.now();
    SWING_V4_BANK.forEach((entry, i) => {
      if (i % part[1]! !== part[0]! - 1) return;
      const proved = proveTall(entry.seed);
      if (proved) out.push(proved);
      else console.log(`course ${entry.seed}: not proved on the taller cavern`);
    });
    console.log(`part ${part.join("/")}: ${out.length} proved in ${((Date.now() - started) / 1000).toFixed(0)} s`);
    const file = rest.find((a) => !a.startsWith("--"));
    if (file) writeFileSync(file, JSON.stringify(out));
    else writeTall(out);
  }
} else if (process.argv[2] === "--merge") {
  write(process.argv.slice(3).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as SwingBankEntry[]));
} else {
  const target = Number(process.argv[2] ?? 300);
  const out: SwingBankEntry[] = [];
  const seen = new Set<number>();
  const started = Date.now();
  let attempts = 0;
  const game = swingGameFor(SWING_REV);
  while (out.length < target && attempts < target * 20) {
    attempts++;
    const seed = arcadeSeed();
    if (seen.has(seed)) continue;
    seen.add(seed);
    if ((game.init(seed).starAnchors ?? []).length !== SWING_STARS) continue;
    const witness = proveSwingSeedV4(seed);
    if (!witness || witness.stars !== SWING_STARS) continue;
    // Replay the witness on the real sim: it must finish with every star.
    let s = game.init(seed);
    const events = new Map(witness.log.map((e) => [e.t, e]));
    while (!s.ended) s = game.step(s, events.get(s.tick + 1) ?? null);
    if (s.ended !== 1 || (s.stars ?? 0) !== SWING_STARS || game.score(s) !== 150) continue;
    out.push({ seed, ticks: s.tick, stars: s.stars ?? 0 });
    if (out.length % 10 === 0) console.log(`${out.length} / ${target} (${attempts} tried, ${((Date.now() - started) / 1000).toFixed(0)} s)`);
  }
  const seconds = (Date.now() - started) / 1000;
  console.log(`built ${out.length}/${target} proved courses in ${seconds.toFixed(1)} s (${attempts} seeds tried, ${((out.length / attempts) * 100).toFixed(1)}% pass rate)`);

  if (process.argv[3]) writeFileSync(process.argv[3], JSON.stringify(out));
  else write(out);
}
