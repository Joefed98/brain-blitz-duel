/**
 * Builds src/lib/duel/levels/codewordExpert.data.ts (the Word overhaul's levels, 15 Nov 2026): the Cryptogrid bank
 * boards Expert deals. Expert starts from the bank entry's own four letters (the rev-1 givens, proven to leave exactly
 * one solution by scripts/codeword-check.ts), and only boards the human-like solver (codewordHuman.server.ts) decodes
 * from those four letters alone, to the real solution, are listed.
 *
 *   bun scripts/codeword-expert-bank.ts           write the list
 *   bun scripts/codeword-expert-bank.ts --check   rebuild in memory and compare (no write)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { CODEWORD_BANK } from "../src/lib/duel/codewordBank.server";
import { codewordFromEntry } from "../src/lib/duel/codeword.server";
import { solveCodewordLikeAHuman } from "../src/lib/duel/levels/codewordHuman.server";

export function expertIndices(): number[] {
  const out: number[] = [];
  CODEWORD_BANK.forEach((entry, index) => {
    const p = codewordFromEntry(entry, 1);
    const r = solveCodewordLikeAHuman(p.cells, p.numbers, p.givens);
    if (r.solved && r.letters.join("") === p.solution) out.push(index);
  });
  return out;
}

const FILE = new URL("../src/lib/duel/levels/codewordExpert.data.ts", import.meta.url);

function render(list: readonly number[]): string {
  const rows: string[] = [];
  for (let i = 0; i < list.length; i += 20) rows.push("  " + list.slice(i, i + 20).join(", ") + ",");
  return `/**
 * Generated by scripts/codeword-expert-bank.ts (do not edit): the ${list.length} of ${CODEWORD_BANK.length} Cryptogrid bank boards that the
 * human-like solver (codewordHuman.server.ts) decodes from their four starting letters alone. Cryptogrid's Expert deals
 * only these (src/lib/duel/levels/codeword.server.ts).
 */
export const CODEWORD_EXPERT_INDICES: readonly number[] = [
${rows.join("\n")}
];
`;
}

if (import.meta.main) {
  const text = render(expertIndices());
  if (process.argv.includes("--check")) {
    const same = readFileSync(FILE, "utf8") === text;
    console.log(same ? "codewordExpert.data.ts rebuilds byte for byte" : "codewordExpert.data.ts differs from a rebuild");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(FILE, text);
  console.log("wrote codewordExpert.data.ts");
}
