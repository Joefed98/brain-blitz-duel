/**
 * Builds a server-only bank of proved Orbit rev3 courses in
 * src/lib/duel/orbitRev3Bank.server.ts, the same way Grappler (Swing) uses
 * scripts/swing-bank.ts. Each entry is a seed/salt (full course rebuilds
 * deterministically from them), the compact 41-planet layout (so rooms never
 * have to rebuild/reprove at play time), the live-bot proof's completion
 * tick, and the bot's tap log (so scripts/orbit-rev3-proof.ts can
 * re-verify an entry instantly by replay instead of re-searching).
 *
 * Proving ~500 courses (2-11s/seed, salted + live-bot proved) takes a while,
 * so this runs here, sharded across parallel worker processes, not while a
 * room starts.
 *
 *   bun scripts/orbit-bank.ts 500                   # build and write (spawns workers)
 *   bun scripts/orbit-bank.ts 60 /tmp/a.json         # one shard (worker mode; merge with --merge)
 *   bun scripts/orbit-bank.ts --merge /tmp/a.json /tmp/b.json ...
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { arcadeSeed } from "../src/lib/duel/arcade.server";
import { buildCourse3, runRev3BotWithTaps, ORBIT_REV3_WORLD_W } from "../src/lib/arcade/orbitRev3";
import { encodeRev3Planets } from "../src/lib/duel/orbitRev3Course.server";
import type { OrbitRev3BankEntry } from "../src/lib/duel/orbitRev3Bank.server";

const OUT = "src/lib/duel/orbitRev3Bank.server.ts";
const WORKERS = 8;

function write(entries: OrbitRev3BankEntry[]) {
  const unique = new Map(entries.map((entry) => [entry.seed, entry]));
  writeFileSync(
    OUT,
    `/* Generated by scripts/orbit-bank.ts — do not edit by hand. */\nimport type { OrbitRev3CompactPlanet } from "./orbitRev3Course.server";\n\nexport interface OrbitRev3BankEntry {\n  seed: number;\n  /** Salt the proof succeeded at (0 = unsalted seed itself). */\n  salt: number;\n  /** Proof-witness completion tick, recorded at build time (not replayed from). */\n  ticks: number;\n  /** Compact per-planet rows, index 0..40 — see encodeRev3Planets/decodeRev3Planets. */\n  planets: OrbitRev3CompactPlanet[];\n  /** Bot tap ticks (ORBIT_INPUT_TAP events), for fast re-verification without re-searching. */\n  taps: number[];\n}\n\nexport const ORBIT_REV3_BANK: OrbitRev3BankEntry[] = ${JSON.stringify([...unique.values()])};\n`,
  );
  console.log(`wrote ${unique.size} courses to ${OUT}`);
}

function buildShard(target: number): OrbitRev3BankEntry[] {
  const out: OrbitRev3BankEntry[] = [];
  const seen = new Set<number>();
  let attempts = 0;
  while (out.length < target && attempts < target * 20) {
    attempts++;
    const seed = arcadeSeed();
    if (seen.has(seed)) continue;
    seen.add(seed);
    let built: ReturnType<typeof buildCourse3>;
    try {
      built = buildCourse3(seed, ORBIT_REV3_WORLD_W);
    } catch {
      continue;
    }
    const { proof, taps } = runRev3BotWithTaps(built.planets, ORBIT_REV3_WORLD_W);
    if (!proof.ok) continue;
    out.push({ seed, salt: built.salt, ticks: proof.ticks, planets: encodeRev3Planets(built.planets), taps });
  }
  return out;
}

if (process.argv[2] === "--merge") {
  write(process.argv.slice(3).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as OrbitRev3BankEntry[]));
} else if (process.argv[3]) {
  // Worker mode: build one shard and write it to the given file.
  const target = Number(process.argv[2] ?? 60);
  const started = Date.now();
  const out = buildShard(target);
  console.log(`shard: built ${out.length}/${target} proved courses in ${((Date.now() - started) / 1000).toFixed(1)} s`);
  writeFileSync(process.argv[3], JSON.stringify(out));
} else {
  // Orchestrator mode: fan out across WORKERS child processes, merge, write.
  const target = Number(process.argv[2] ?? 500);
  const perWorker = Math.ceil(target / WORKERS);
  const parts = Array.from({ length: WORKERS }, (_, w) => `/tmp/orbit-bank-part-${w}.json`);
  const started = Date.now();
  console.log(`spawning ${WORKERS} workers for ${target} courses (${perWorker} each)...`);
  const procs = parts.map((out) =>
    Bun.spawn(["bun", "run", "scripts/orbit-bank.ts", String(perWorker), out], { stdout: "inherit", stderr: "inherit" }),
  );
  const codes = await Promise.all(procs.map((p) => p.exited));
  codes.forEach((code, i) => {
    if (code !== 0) throw new Error(`worker ${i} exited ${code}`);
  });
  const seconds = (Date.now() - started) / 1000;
  const entries = parts.flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as OrbitRev3BankEntry[]);
  console.log(`built ${entries.length} proved courses across ${WORKERS} workers in ${seconds.toFixed(1)} s`);
  write(entries.slice(0, target));
}
