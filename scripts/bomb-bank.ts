/**
 * Builds the six-step Bomb Defusal bank in src/lib/duel/bombBank.server.ts.
 *
 *   bun scripts/bomb-bank.ts 300            # build and write
 *   bun scripts/bomb-bank.ts 75 /tmp/a.json # one shard (merge with --merge)
 *   bun scripts/bomb-bank.ts --merge /tmp/a.json /tmp/b.json ...
 *
 * Each panel comes from generateBombPanel(2): a random six-action plan, a
 * randomised greedy narrowing over the rules true of it until only the plan
 * survives all 60,480 ordered six-action sequences, then pruning so every
 * rule on the card is individually necessary (6–9 rules, at most three per
 * family). The search takes seconds per panel, so it runs here, not at room
 * start.
 */
import { readFileSync, writeFileSync } from "node:fs";

import { generateBombPanel } from "../src/lib/duel/bomb.server";
import type { BombPuzzleData } from "../src/lib/duel/types";

const OUT = "src/lib/duel/bombBank.server.ts";

function write(entries: BombPuzzleData[]) {
  const unique = new Map(entries.map((entry) => [JSON.stringify(entry), entry]));
  writeFileSync(
    OUT,
    `/* Generated by scripts/bomb-bank.ts — do not edit by hand. */\nimport type { BombPuzzleData } from "./types";\n\nexport const BOMB_V2_BANK: BombPuzzleData[] = ${JSON.stringify([...unique.values()])};\n`,
  );
  console.log(`wrote ${unique.size} panels to ${OUT}`);
}

if (process.argv[2] === "--merge") {
  write(process.argv.slice(3).flatMap((file) => JSON.parse(readFileSync(file, "utf8")) as BombPuzzleData[]));
} else {
  const count = Number(process.argv[2] ?? 300);
  const out: BombPuzzleData[] = [];
  const started = Date.now();
  for (let i = 0; i < count; i++) out.push(generateBombPanel(2).puzzle);
  console.log(`built ${count} panels in ${((Date.now() - started) / 1000).toFixed(0)} s`);
  if (process.argv[3]) writeFileSync(process.argv[3], JSON.stringify(out));
  else write(out);
}
