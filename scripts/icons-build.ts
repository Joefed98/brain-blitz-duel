/**
 * Builds the Joulz icon set into the app (icon swap, 7 Nov 2026; presentation only).
 *
 * Reads the approved SVGs in docs/icons/svg/ (24 × 24, 2 px stroke, currentColor; docs/icons/README.md) and
 * writes src/design/icons/icons.data.ts: each icon's inner markup keyed by its file name, so the Icon
 * component (src/design/components/Icon.tsx) inlines them in the bundle with no network request.
 *
 *   bun scripts/icons-build.ts           write the data file
 *   bun scripts/icons-build.ts --check   fail if the data file is not exactly what the SVGs give
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ICON_SVG_DIR = "docs/icons/svg";
export const ICON_NAMES_FILE = "docs/icons/names.json";
export const ICON_DATA_FILE = "src/design/icons/icons.data.ts";

/** The markup inside one approved file's <svg> root, whose viewBox must be 0 0 24 24. */
export function iconBody(file: string, source: string): string {
  const m = /^<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(source.trim());
  if (!m) throw new Error(`${file}: not a single <svg> element`);
  if (!/viewBox=['"]0 0 24 24['"]/.test(m[1]!)) throw new Error(`${file}: viewBox is not 0 0 24 24`);
  return m[2]!.trim();
}

export function iconFiles(): string[] {
  return readdirSync(ICON_SVG_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort();
}

/** names.json's label for a file; an `-on` file is its tab icon's filled, active version. */
export function iconLabel(name: string, labels: Record<string, string>): string {
  const on = /-on$/.test(name);
  const label = labels[on ? name.slice(0, -3) : name];
  if (!label) throw new Error(`${name}.svg has no label in docs/icons/names.json`);
  return on ? `${label} (active)` : label;
}

export function buildIconData(): string {
  const labels = JSON.parse(readFileSync(ICON_NAMES_FILE, "utf8")) as Record<string, string>;
  const names = iconFiles().map((file) => file.replace(/\.svg$/, ""));
  const lines = iconFiles().map((file) => {
    const name = file.replace(/\.svg$/, "");
    const body = iconBody(file, readFileSync(join(ICON_SVG_DIR, file), "utf8"));
    return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
  });
  return [
    "// Generated by scripts/icons-build.ts from docs/icons/svg/ (the approved Joulz icons). Do not edit:",
    "// change the SVGs and run `bun scripts/icons-build.ts`.",
    "export const ICON_BODIES = {",
    ...lines,
    "} as const;",
    "",
    "/** Each icon's label (docs/icons/names.json), for the gallery and any accessible name. */",
    "export const ICON_LABELS: Record<keyof typeof ICON_BODIES, string> = {",
    ...names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(iconLabel(name, labels))},`),
    "};",
    "",
    "export type IconName = keyof typeof ICON_BODIES;",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const next = buildIconData();
  if (process.argv.includes("--check")) {
    const now = readFileSync(ICON_DATA_FILE, "utf8");
    if (now !== next) {
      console.error(`FAIL ${ICON_DATA_FILE} is out of date: run bun scripts/icons-build.ts`);
      process.exit(1);
    }
    console.log(`ok ${ICON_DATA_FILE} matches ${ICON_SVG_DIR}`);
  } else {
    writeFileSync(ICON_DATA_FILE, next);
    console.log(`wrote ${ICON_DATA_FILE} (${iconFiles().length} icons)`);
  }
}
