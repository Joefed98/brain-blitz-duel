/**
 * The Tournaments, Leaderboards and Daily pages' art (phase 2 step 3, 14 Nov 2026): the style guide's 3D art-kit icons
 * (docs/design/style-guide/art/*.png, 192 px renders) cut to the size the list rows draw them (44 px), at 1x, 2x and
 * 3x, as WebP in public/tournaments-art/, plus src/components/tournaments/tournamentArt.data.ts. The same method as
 * scripts/nav-art.ts (never upscaled).
 *
 *   bun scripts/tournament-art.ts          rebuild
 *   bun scripts/tournament-art.ts --check  rebuild in memory and fail if anything on disk differs (tournament-art-check)
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, loadImage } from "@napi-rs/canvas";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "docs/design/style-guide/art");
const OUT = join(ROOT, "public/tournaments-art");
const DATA = join(ROOT, "src/components/tournaments/tournamentArt.data.ts");

/** Every image these pages draw: its art-kit source, the CSS px it is drawn at, and what it shows. */
export const ART = {
  arena: { src: "arena", px: 44, alt: "Arena" },
  scoreAttack: { src: "quest", px: 44, alt: "Score Attack" },
  cup: { src: "trophy", px: 44, alt: "Category Cup" },
  championship: { src: "leaderboards", px: 44, alt: "Joulz Championship" },
  publicGame: { src: "rooms", px: 44, alt: "Public game" },
  rating: { src: "rated", px: 44, alt: "Joulz Rating" },
  puzzles: { src: "puzzles", px: 44, alt: "Puzzles" },
  arcade: { src: "arcade", px: 44, alt: "Arcade" },
  daily: { src: "daily", px: 44, alt: "Daily" },
  plus: { src: "plus", px: 44, alt: "Joulz Plus" },
  board: { src: "leaderboards", px: 44, alt: "Leaderboard" },
  trophy: { src: "trophy", px: 96, alt: "A gold trophy" },
} as const;

export type TournamentArtName = keyof typeof ART;

async function build(): Promise<{ files: Map<string, Buffer>; data: string }> {
  const files = new Map<string, Buffer>();
  const entries: string[] = [];
  for (const [name, spec] of Object.entries(ART)) {
    const image = await loadImage(readFileSync(join(SOURCE, `${spec.src}.png`)));
    const urls: string[] = [];
    for (const scale of [1, 2, 3]) {
      const size = spec.px * scale;
      if (size > image.width) continue;
      const canvas = createCanvas(size, size);
      const ctx = canvas.getContext("2d");
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, size, size);
      const bytes = Buffer.from(await canvas.encode("webp", 88));
      const file = `${name}-${scale}x.webp`;
      files.set(file, bytes);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      urls.push(`"/tournaments-art/${file}?v=${hash}"`);
    }
    entries.push(`  ${name}: { px: ${spec.px}, alt: ${JSON.stringify(spec.alt)}, urls: [${urls.join(", ")}] },`);
  }
  const data = `// Generated by scripts/tournament-art.ts from docs/design/style-guide/art; do not edit by hand.\n// urls: 1x, 2x and (where the 192 px source allows) 3x WebP.\nexport const TOURNAMENT_ART = {\n${entries.join("\n")}\n} as const;\n\nexport type TournamentArtName = keyof typeof TOURNAMENT_ART;\n`;
  return { files, data };
}

const check = process.argv.includes("--check");
const { files, data } = await build();
let total = 0;
for (const b of files.values()) total += b.length;
if (check) {
  const problems: string[] = [];
  for (const [file, bytes] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) problems.push(`public/tournaments-art/${file} differs`);
  }
  if (!existsSync(DATA) || readFileSync(DATA, "utf8") !== data) problems.push("tournamentArt.data.ts differs");
  if (problems.length) {
    console.log(`FAIL: ${problems.join("; ")} (run bun scripts/tournament-art.ts)`);
    process.exit(1);
  }
  console.log(`tournament art matches: ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, bytes] of files) writeFileSync(join(OUT, file), bytes);
  writeFileSync(DATA, data);
  console.log(`wrote ${files.size} files, ${(total / 1024).toFixed(1)} KB`);
}
