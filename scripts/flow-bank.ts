/**
 * Builds the Chroma Lines (`flow`) banks.
 *
 *   bun scripts/flow-bank.ts                         rebuild and write Normal's bank (src/lib/duel/flowBank.server.ts)
 *   bun scripts/flow-bank.ts --check                 rebuild Normal's and confirm it matches the committed file
 *   bun scripts/flow-bank.ts --level=hard [--check]  the same for a level's own bank (easy, hard, expert; levels,
 *                                                    16 Nov 2026: src/lib/duel/flow<Level>Bank.server.ts)
 *   bun scripts/flow-bank.ts --level=all [--check]   every level's bank
 *
 * Normal: every entry is the live generator under a fixed seed, re-verified exactly as the generator accepts a board
 * (see scripts/puzzle-bank-lib.ts). A level: entry i is the level's generator under flowLevelSeed(level, i, retry) for
 * the smallest retry whose board passes verifyFlowLevelPuzzle (the level's rules, the exhaustive uniqueness proof and
 * the human-style solver) and isn't a duplicate of an earlier entry. No clock, CSPRNG or scheduling affects it.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { runBankScript } from "./puzzle-bank-lib";

const args = process.argv.slice(2);
const levelArg = args.find((a) => a.startsWith("--level="))?.slice("--level=".length);

/** A level bank may not need more retries than this for one index. */
const MAX_LEVEL_RETRIES = 64;

export async function buildLevelBank(level: "easy" | "hard" | "expert", count?: number) {
  const { buildFlowLevelEntry, flowLevelKey, flowLevelSeed, flowLevelSettings } = await import("../src/lib/duel/flowLevels.server");
  const size = count ?? flowLevelSettings(level).bankSize;
  const seen = new Set<string>();
  const entries: unknown[] = [];
  const retries: number[] = [];
  for (let index = 0; index < size; index++) {
    let found = false;
    for (let retry = 0; retry < MAX_LEVEL_RETRIES; retry++) {
      const puzzle = buildFlowLevelEntry(level, flowLevelSeed(level, index, retry));
      if (!puzzle) continue;
      const key = flowLevelKey(puzzle);
      if (seen.has(key)) continue;
      seen.add(key);
      entries.push(puzzle);
      retries.push(retry);
      found = true;
      break;
    }
    if (!found) throw new Error(`flow ${level} bank entry ${index}: no board in ${MAX_LEVEL_RETRIES} seeds`);
    if ((index + 1) % 100 === 0) console.error(`[flow ${level}] ${index + 1}/${size}`);
  }
  const L = level[0]!.toUpperCase() + level.slice(1);
  const U = level.toUpperCase();
  const sha = createHash("sha256").update(JSON.stringify(entries)).digest("hex");
  const source = `/* Generated by scripts/flow-bank.ts --level=${level} — do not edit by hand. Rebuild with \`bun scripts/flow-bank.ts --level=${level}\`. */
import type { FlowPuzzleData } from "./types";

/** Build facts: entry i is the ${level} generator under flowLevelSeed("${level}", i, FLOW_${U}_BANK_RETRIES[i]) (flowLevels.server.ts). */
export const FLOW_${U}_BANK_BUILD = { entries: ${entries.length}, sha256: "${sha}" } as const;

export const FLOW_${U}_BANK_RETRIES: number[] = ${JSON.stringify(retries)};

export const FLOW_${U}_BANK: FlowPuzzleData[] = [
${entries.map((e) => `  ${JSON.stringify(e)},`).join("\n")}
];
`;
  return { file: fileURLToPath(new URL(`../src/lib/duel/flow${L}Bank.server.ts`, import.meta.url)), source, entries: entries.length };
}

if (import.meta.main) {
  if (!levelArg) {
    await runBankScript("flow");
  } else {
    const levels = levelArg === "all" ? (["easy", "hard", "expert"] as const) : [levelArg as "easy" | "hard" | "expert"];
    const check = args.includes("--check");
    let failed = false;
    for (const level of levels) {
      if (!["easy", "hard", "expert"].includes(level)) throw new Error(`unknown level ${level}`);
      const t0 = Date.now();
      const built = await buildLevelBank(level);
      const seconds = ((Date.now() - t0) / 1000).toFixed(1);
      if (check) {
        const same = readFileSync(built.file, "utf8") === built.source;
        console.log(`${same ? "PASS" : "FAIL"} flow ${level}: rebuild of ${built.entries} entries ${same ? "matches" : "differs from"} the committed bank (${seconds} s)`);
        if (!same) failed = true;
      } else {
        writeFileSync(built.file, built.source);
        console.log(`flow ${level}: wrote ${built.entries} entries, ${(Buffer.byteLength(built.source) / 1024).toFixed(0)} KB (${seconds} s)`);
      }
    }
    if (failed) process.exit(1);
  }
}
