/**
 * Builds Exact's bank of Normal-style targets a person can work out (D2, 22 Nov 2026; targetRounds.ts): Expert's round
 * of targets opens on two of them, and Expert deals from banks in milliseconds (Joe, 16 Nov 2026: no live search of up
 * to 3 s). Every board is today's Normal deal (target.ts generateTargetPuzzle, 1 or 2 large numbers, a target of 101–999)
 * kept only when the person-like solver (targetLevels.server.ts personSolveTarget) reaches it, each under its own fixed
 * seed, so the bank rebuilds byte for byte. Duplicate boards are skipped.
 *
 *   bun scripts/target-round-bank.ts            write src/lib/duel/targetRoundBank.server.ts
 *   bun scripts/target-round-bank.ts --check    rebuild in memory and compare
 */
import { readFileSync, writeFileSync } from "node:fs";

import { withSeededRandom } from "../src/lib/duel/random";
import { generateTargetPuzzle } from "../src/lib/duel/target";
import { personSolveTarget } from "../src/lib/duel/targetLevels.server";
import type { TargetStep } from "../src/lib/duel/types";

export const TARGET_ROUND_BANK_SIZE = 400;
const SEED_BASE = 0x7a1f_0000;
const OUT = new URL("../src/lib/duel/targetRoundBank.server.ts", import.meta.url);

export type TargetRoundBoard = { tiles: number[]; target: number; solution: TargetStep[] };

export function buildTargetRoundBank(size = TARGET_ROUND_BANK_SIZE): TargetRoundBoard[] {
  const seen = new Set<string>();
  const out: TargetRoundBoard[] = [];
  for (let i = 0; out.length < size; i++) {
    const p = withSeededRandom(SEED_BASE + i, () => generateTargetPuzzle());
    if (!personSolveTarget(p.tiles, p.target)) continue;
    const key = `${[...p.tiles].sort((a, b) => a - b).join(",")}>${p.target}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ tiles: p.tiles, target: p.target, solution: p.solution });
  }
  return out;
}

function render(bank: TargetRoundBoard[]): string {
  return `/** Generated by scripts/target-round-bank.ts. Exact's Normal-style targets a person can work out (today's Normal rule: 1 or 2 large numbers, a target of 101–999, each reached by the person-like solver), for Expert's round of targets. */\nimport type { TargetStep } from "./types";\n\nexport const TARGET_ROUND_BANK: { tiles: number[]; target: number; solution: TargetStep[] }[] = [\n${bank.map((b) => `  ${JSON.stringify(b)},`).join("\n")}\n];\n`;
}

if (import.meta.main) {
  const t0 = performance.now();
  const text = render(buildTargetRoundBank());
  if (process.argv.includes("--check")) {
    const same = readFileSync(OUT, "utf8") === text;
    console.log(same ? "PASS: the Exact round bank rebuilds byte for byte" : "FAIL: the Exact round bank differs from a rebuild");
    if (!same) process.exit(1);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.pathname} (${Math.round(text.length / 1024)} KB) in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
  }
}
