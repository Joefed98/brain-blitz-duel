/**
 * Writes src/lib/duel/revealPalette.data.ts: each game's answer-reveal gradient.
 *
 *   bun scripts/reveal-palette.ts          write the file
 *   bun scripts/reveal-palette.ts --check  exit 1 if the file differs from what the rules give (reveal-palette-check runs this)
 *
 * The colours (3 Nov 2026, Joe's audit: gradients sampled from the tiles blended two muddy hues, Breaker brown to red,
 * Meteor mustard, Jaywalk blue to red): one hue per game, deep at the top and fading to near-black. An arcade game takes
 * its curated hue (REVEAL_ARCADE_HUES in revealPalette.ts); every puzzle takes its category's own colour (theme
 * tokens, REVEAL_CATEGORY_COLOURS), so a category reads as a set. Each stop is darkened (keeping its hue) until white
 * text on it reads at least REVEAL_MIN_CONTRAST:1. Deterministic.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { ACTIVE_PUZZLE_TYPES, RETIRED_PUZZLE_TYPES, puzzleDef } from "../src/lib/duel/registry";
import { REVEAL_ARCADE_HUES, REVEAL_CATEGORY_COLOURS, REVEAL_MIN_CONTRAST, hexToRgb, rgbToHex, whiteContrast } from "../src/lib/duel/revealPalette";

const OUT = "src/lib/duel/revealPalette.data.ts";

type Rgb = [number, number, number];

/** A fully saturated colour of a hue (HSV, value 1). */
function hueRgb(h: number, s = 0.82): Rgb {
  const c = s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = 1 - c;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [(r + m) * 255, (g + m) * 255, (b + m) * 255];
}

/** Scales a colour towards black (its hue and saturation kept) until white on it reads `contrast`:1. */
function darkenTo(rgb: Rgb, contrast: number): Rgb {
  let k = 1;
  let out = rgb;
  while (whiteContrast(out) < contrast && k > 0.02) {
    k -= 0.005;
    out = [rgb[0] * k, rgb[1] * k, rgb[2] * k];
  }
  return out.map((v) => Math.round(v)) as Rgb;
}

/** One hue, deep at the top, darker in the middle, near-black at the bottom. */
function gradientOf(base: Rgb): [string, string, string] {
  const top = darkenTo(base, REVEAL_MIN_CONTRAST + 1);
  const mid = darkenTo(base, REVEAL_MIN_CONTRAST + 5);
  const bottom = top.map((v) => Math.round(v * 0.28)) as Rgb;
  return [rgbToHex(top), rgbToHex(mid), rgbToHex(bottom)];
}

const entries: [string, [string, string, string]][] = [];
for (const type of [...new Set([...ACTIVE_PUZZLE_TYPES, ...RETIRED_PUZZLE_TYPES])].sort()) {
  const category = puzzleDef(type).category;
  const hue = category === "arcade" ? REVEAL_ARCADE_HUES[type] : undefined;
  const base: Rgb = hue !== undefined ? hueRgb(hue) : (hexToRgb(REVEAL_CATEGORY_COLOURS[category] ?? REVEAL_CATEGORY_COLOURS["arcade"]!) as Rgb);
  entries.push([type, gradientOf(base)]);
}

const text = `/**
 * Generated by \`bun scripts/reveal-palette.ts\`; do not edit. Each game's answer reveal gradient [top, middle,
 * bottom] (revealPalette.ts): one hue per game (an arcade game's curated hue, a puzzle's category colour), deep at the
 * top and fading to near-black, darkened so white text reads at least ${REVEAL_MIN_CONTRAST}:1 on every stop.
 */
export const REVEAL_PALETTE: Readonly<Record<string, readonly [string, string, string]>> = {
${entries.map(([t, [a, b, c]]) => `  ${/^[a-z][a-z0-9]*$/i.test(t) ? t : JSON.stringify(t)}: ["${a}", "${b}", "${c}"],`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== text) {
    console.log(`FAIL ${OUT} is out of date: run bun scripts/reveal-palette.ts`);
    process.exit(1);
  }
  console.log(`PASS ${OUT} matches the colour rules (${entries.length} games)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}: ${entries.length} games`);
}
