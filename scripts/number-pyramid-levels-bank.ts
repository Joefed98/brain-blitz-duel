/**
 * Builds Integer Pyramid's level banks (stage 3 of the Number overhaul, 15 Nov 2026): for Easy, Hard and Expert, sets
 * of four rising boards from the registry's settings (src/lib/levels/gameLevels.ts), each proved to have exactly one
 * tray assignment (decoys included) and completed by the person-like solver (numberPyramidLevels.ts: every stone
 * forced by a sum or by the only tile that fits). Seeded, so it rebuilds byte for byte.
 *
 *   bun scripts/number-pyramid-levels-bank.ts            write src/lib/duel/numberPyramidLevelsBank.server.ts
 *   bun scripts/number-pyramid-levels-bank.ts --check    rebuild in memory and compare
 */
import { readFileSync, writeFileSync } from "node:fs";

import { npBuild } from "../src/lib/duel/numberPyramid";
import { npCountSolutionsFast, npPersonSolve, type NpLevelSettings, type NpLevelStage } from "../src/lib/duel/numberPyramidLevels";
import { gameLevelSettings } from "../src/lib/levels/gameLevels";

export const NP_LEVEL_SETS = 200;
const LEVELS = ["easy", "hard", "expert"] as const;
const OUT = new URL("../src/lib/duel/numberPyramidLevelsBank.server.ts", import.meta.url);

function rng(seed: number) {
  let a = seed >>> 0;
  return (n: number) => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return Math.floor((((t ^ (t >>> 14)) >>> 0) / 4294967296) * n);
  };
}

type Board = { rows: 4 | 5 | 6; givens: (number | null)[]; tray: number[]; solution: number[] };

function build(rand: (n: number) => number, stage: NpLevelStage, decoyCount: number): Board | null {
  const shuffle = <T,>(a: T[]) => {
    for (let i = a.length - 1; i > 0; i--) { const j = rand(i + 1); [a[i], a[j]] = [a[j]!, a[i]!]; }
    return a;
  };
  const bottom = Array.from({ length: stage.rows }, () => stage.bottomLo + rand(stage.bottomHi - stage.bottomLo + 1));
  const solution = npBuild(bottom);
  const empty = stage.minEmpty + rand(stage.maxEmpty - stage.minEmpty + 1);
  const cells = shuffle([...Array(solution.length).keys()]).slice(0, empty).sort((a, b) => a - b);
  const givens = solution.map((v, i) => (cells.includes(i) ? null : v));
  const lo = Math.min(...solution), hi = Math.max(...solution);
  const missing = cells.map((c) => solution[c]!);
  const decoys: number[] = [];
  for (let tries = 0; decoys.length < decoyCount && tries < 80; tries++) {
    const base = missing[rand(missing.length)]!;
    const d = base + (rand(2) ? 1 : -1) * (1 + rand(3));
    if (d < lo || d > hi || d < 1) continue;
    decoys.push(d);
  }
  if (decoys.length < decoyCount) return null;
  const tray = shuffle([...missing, ...decoys]);
  if (npCountSolutionsFast(givens, tray, stage.rows, 2) !== 1) return null;
  if (!npPersonSolve(givens, tray, stage.rows, solution).solved) return null;
  return { rows: stage.rows, givens, tray, solution };
}

export function buildLevelBank(level: (typeof LEVELS)[number]): { sets: Board[][]; attempts: number } {
  const settings = gameLevelSettings<NpLevelSettings>("numpyramid", level);
  if (!settings) throw new Error(`numpyramid offers no ${level} level`);
  const rand = rng(0x9e3779b9 ^ (LEVELS.indexOf(level) + 1) * 7919);
  const seen = new Set<string>();
  const sets: Board[][] = [];
  let attempts = 0;
  while (sets.length < NP_LEVEL_SETS) {
    const set: Board[] = [];
    for (const stage of settings.stages) {
      let board: Board | null = null;
      for (let tries = 0; tries < 20000 && !board; tries++) {
        attempts++;
        const candidate = build(rand, stage, settings.decoys);
        if (!candidate) continue;
        const key = JSON.stringify(candidate.givens) + JSON.stringify([...candidate.tray].sort((a, b) => a - b));
        if (seen.has(key)) continue;
        seen.add(key);
        board = candidate;
      }
      if (!board) throw new Error(`numpyramid ${level}: no board for ${JSON.stringify(stage)}`);
      set.push(board);
    }
    sets.push(set);
  }
  return { sets, attempts };
}

function render(banks: Record<string, Board[][]>): string {
  const body = LEVELS.map((level) => `  ${level}: ${JSON.stringify(banks[level]!.map((pyramids) => ({ pyramids })))},`).join("\n");
  return `/** Generated by scripts/number-pyramid-levels-bank.ts. Integer Pyramid's Easy, Hard and Expert sets: every board has exactly one tray assignment and is completed by the person-like solver. */\nimport type { NumberPyramidBankEntry } from "./numberPyramidLevelsBankTypes";\n\nexport const NUMBER_PYRAMID_LEVEL_BANKS: Record<"easy" | "hard" | "expert", NumberPyramidBankEntry[]> = {\n${body}\n};\n`;
}

if (import.meta.main) {
  const t0 = performance.now();
  const banks: Record<string, Board[][]> = {};
  for (const level of LEVELS) {
    const { sets, attempts } = buildLevelBank(level);
    banks[level] = sets;
    console.log(`${level}: ${sets.length} sets from ${attempts} attempts`);
  }
  const text = render(banks);
  if (process.argv.includes("--check")) {
    const same = readFileSync(OUT, "utf8") === text;
    console.log(same ? "PASS: the level banks rebuild byte for byte" : "FAIL: the level banks differ from a rebuild");
    if (!same) process.exit(1);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.pathname} (${Math.round(text.length / 1024)} KB) in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
  }
}
