/**
 * Builds the Trail bank in src/lib/duel/trailBank.server.ts.
 *
 *   bun scripts/trail-bank.ts
 *
 * Answer-first: a random king-move Hamiltonian path on 6×6 (randomised
 * Warnsdorff walk with restarts). Starting from every step given, steps are
 * dropped in random order whenever the backtracking solver still finds only
 * one path, leaving an irreducible set. That is repeated 8 times per path with
 * different orders and the smallest set kept (smallest found, not a proven
 * global minimum). Paths needing more than 12 are rejected; sets under 8 are
 * topped up with random extra steps to reach 8.
 */
import { writeFileSync } from "node:fs";

import { trCountSolutions, trNeighbours, TR_CELLS, TR_MAX_GIVENS, TR_MIN_GIVENS } from "../src/lib/duel/trail";

const BANK = Number(process.argv[2] ?? 300);
const TRIES_PER_PATH = 8;
const rand = (n: number) => Math.floor(Math.random() * n);
const shuffle = <T,>(a: T[]) => {
  for (let i = a.length - 1; i > 0; i--) {
    const j = rand(i + 1);
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
};

function randomPath(): number[] {
  for (;;) {
    const used = new Uint8Array(TR_CELLS);
    let cell = rand(TR_CELLS);
    const path = [cell];
    used[cell] = 1;
    while (path.length < TR_CELLS) {
      const options = shuffle(trNeighbours(cell).filter((n) => !used[n]));
      if (!options.length) break;
      const deg = (c: number) => trNeighbours(c).filter((n) => !used[n] && n !== c).length;
      options.sort((a, b) => deg(a) - deg(b));
      // mostly Warnsdorff, sometimes the second choice for variety
      cell = options.length > 1 && Math.random() < 0.15 ? options[1]! : options[0]!;
      used[cell] = 1;
      path.push(cell);
    }
    if (path.length === TR_CELLS) return path;
  }
}

function givensFor(path: number[], steps: Set<number>): (number | null)[] {
  const g: (number | null)[] = new Array(TR_CELLS).fill(null);
  for (const s of steps) g[path[s - 1]!] = s;
  return g;
}

/** Start from every step given; drop steps in random order while the path stays unique. */
function minimalGivens(path: number[]): Set<number> {
  const steps = new Set(Array.from({ length: TR_CELLS }, (_, i) => i + 1));
  for (const s of shuffle([...steps].filter((s) => s !== 1 && s !== TR_CELLS))) {
    steps.delete(s);
    if (trCountSolutions(givensFor(path, steps), 2) !== 1) steps.add(s);
  }
  return steps;
}

const bank: { givens: (number | null)[]; solution: number[]; minimal: number }[] = [];
const minimalDist = new Map<number, number>();
const finalDist = new Map<number, number>();
let rejected = 0;
const t0 = Date.now();
while (bank.length < BANK) {
  const path = randomPath();
  let best: Set<number> | null = null;
  for (let t = 0; t < TRIES_PER_PATH; t++) {
    const s = minimalGivens(path);
    if (s && (!best || s.size < best.size)) best = s;
  }
  if (!best || best.size > TR_MAX_GIVENS) {
    rejected++;
    continue;
  }
  const minimal = best.size;
  const pad = shuffle(Array.from({ length: TR_CELLS - 2 }, (_, i) => i + 2).filter((s) => !best!.has(s)));
  while (best.size < TR_MIN_GIVENS) best.add(pad.pop()!);
  const givens = givensFor(path, best);
  if (trCountSolutions(givens, 2) !== 1) throw new Error("not unique");
  minimalDist.set(minimal, (minimalDist.get(minimal) ?? 0) + 1);
  finalDist.set(best.size, (finalDist.get(best.size) ?? 0) + 1);
  bank.push({ givens, solution: path, minimal });
  if (bank.length % 10 === 0) console.log(`${bank.length} built (${((Date.now() - t0) / 1000).toFixed(1)} s)`);
}

const fmt = (m: Map<number, number>) => [...m.entries()].sort((a, b) => a[0] - b[0]).map(([k, v]) => `${k}: ${v}`).join(", ");
console.log(`rejected paths (needed more than ${TR_MAX_GIVENS}): ${rejected}`);
console.log(`smallest unique set found, per board: ${fmt(minimalDist)}`);
console.log(`givens stored, per board (topped up to ${TR_MIN_GIVENS}): ${fmt(finalDist)}`);

const out = `/* Generated by scripts/trail-bank.ts — do not edit by hand. */
export interface TrailBankEntry {
  givens: (number | null)[];
  solution: number[];
}

export const TRAIL_BANK: TrailBankEntry[] = ${JSON.stringify(bank.map(({ givens, solution }) => ({ givens, solution })))};
`;
if (!process.argv[2]) writeFileSync(new URL("../src/lib/duel/trailBank.server.ts", import.meta.url), out);
