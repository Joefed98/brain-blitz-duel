/**
 * Builds src/lib/duel/practiceStamps.data.ts: the version-stamp signature (practiceStamps.ts
 * stampSignature) of the public puzzle every registered game deals today, so the practice list can
 * show the best kept under the current rules before a puzzle is made. Each game is dealt from three
 * bank seeds; a game whose seeds deal different stamps fails (its best would have no one key).
 *
 *   bun scripts/practice-stamps.ts           (writes the file)
 *   bun scripts/practice-stamps.ts --check   (no write; exits 1 if the file is out of date)
 *
 * Re-run it after any change to a version stamp a generator deals; practice-bests-check fails until then.
 */
import { readFileSync, writeFileSync } from "node:fs";

import { generatePuzzle } from "../src/lib/duel/generate.server";
import { PUZZLE_REGISTRY } from "../src/lib/duel/registry";
import { splitPuzzle } from "../src/lib/duel/secrets";
import { stampSignature } from "../src/lib/duel/practiceStamps";
import type { PuzzleType } from "../src/lib/duel/types";

const FILE = "src/lib/duel/practiceStamps.data.ts";

export function buildPracticeStamps(): { table: Record<string, string>; problems: string[] } {
  const table: Record<string, string> = {};
  const problems: string[] = [];
  for (const type of Object.keys(PUZZLE_REGISTRY).sort() as PuzzleType[]) {
    const seen = new Set<string>();
    for (const bankSeed of [101, 20261017, 987654321]) {
      try {
        seen.add(stampSignature(splitPuzzle(generatePuzzle(type, { unblockRow: null, bankSeed })).pub));
      } catch (error) {
        problems.push(`${type}: could not deal a puzzle (${String((error as Error).message ?? error).split("\n")[0]})`);
      }
    }
    if (seen.size > 1) problems.push(`${type}: dealt different stamps (${[...seen].join(" | ")})`);
    table[type] = [...seen][0] ?? "";
  }
  return { table, problems };
}

export function practiceStampsSource(table: Record<string, string>): string {
  const rows = Object.entries(table).map(([type, sig]) => `  ${JSON.stringify(type)}: ${JSON.stringify(sig)},`);
  return [
    "// Generated by scripts/practice-stamps.ts: the version stamps each game deals today. Do not edit.",
    "export const PRACTICE_STAMPS = {",
    ...rows,
    "} as const;",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const { table, problems } = buildPracticeStamps();
  for (const p of problems) console.error(`FAIL ${p}`);
  const source = practiceStampsSource(table);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(FILE, "utf8");
    } catch {
      /* missing */
    }
    if (current !== source) {
      console.error(`FAIL ${FILE} is out of date: run bun scripts/practice-stamps.ts`);
      process.exit(1);
    }
    console.log(`${FILE} is current (${Object.keys(table).length} games)`);
  } else {
    writeFileSync(FILE, source);
    console.log(`wrote ${FILE} (${Object.keys(table).length} games)`);
  }
  if (problems.length) process.exit(1);
}
