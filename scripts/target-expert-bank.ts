/**
 * Builds Exact's Expert bank (Number overhaul, Joe's final push of 16 Nov 2026): Expert deals from this proved bank
 * instead of searching live (the person-like filter took up to 3 s a deal). Every board is made by the same rule the
 * live deal used, `generateTargetLevel` with the registry's Expert settings (small numbers only, a target of 500–999
 * that needs all six, and the person-like solver reaches it), each under its own fixed seed, so the bank rebuilds byte
 * for byte. Duplicate boards are skipped.
 *
 *   bun scripts/target-expert-bank.ts            write src/lib/duel/targetExpertBank.server.ts
 *   bun scripts/target-expert-bank.ts --check    rebuild in memory and compare
 */
import { readFileSync, writeFileSync } from "node:fs";

import { withSeededRandom } from "../src/lib/duel/random";
import { TARGET_EXPERT_BANK_RULE, generateTargetLevel } from "../src/lib/duel/targetLevels.server";
import type { TargetStep } from "../src/lib/duel/types";

export const TARGET_EXPERT_BANK_SIZE = 320;
const OUT = new URL("../src/lib/duel/targetExpertBank.server.ts", import.meta.url);
const SEED_BASE = 0x7a1e_0000;

export type TargetExpertBoard = { tiles: number[]; target: number; solution: TargetStep[] };

export function buildTargetExpertBank(size = TARGET_EXPERT_BANK_SIZE): TargetExpertBoard[] {
  // The bank's own rule (D2, 22 Nov 2026: the registry's Expert is now a round of targets ending on a bank board).
  const settings = TARGET_EXPERT_BANK_RULE;
  const seen = new Set<string>();
  const out: TargetExpertBoard[] = [];
  for (let i = 0; out.length < size; i++) {
    const p = withSeededRandom(SEED_BASE + i, () => generateTargetLevel(settings));
    const key = `${[...p.tiles].sort((a, b) => a - b).join(",")}>${p.target}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ tiles: p.tiles, target: p.target, solution: p.solution });
  }
  return out;
}

function render(bank: TargetExpertBoard[]): string {
  return `/** Generated by scripts/target-expert-bank.ts. Exact's Expert boards: small numbers only, a target of 500–999 that needs all six numbers, each reached by the person-like solver. */\nimport type { TargetStep } from "./types";\n\nexport const TARGET_EXPERT_BANK: { tiles: number[]; target: number; solution: TargetStep[] }[] = [\n${bank.map((b) => `  ${JSON.stringify(b)},`).join("\n")}\n];\n`;
}

if (import.meta.main) {
  const t0 = performance.now();
  const text = render(buildTargetExpertBank());
  if (process.argv.includes("--check")) {
    const same = readFileSync(OUT, "utf8") === text;
    console.log(same ? "PASS: the Exact Expert bank rebuilds byte for byte" : "FAIL: the Exact Expert bank differs from a rebuild");
    if (!same) process.exit(1);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.pathname} (${Math.round(text.length / 1024)} KB) in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
  }
}
