/**
 * The shop's item pictures (wave 2, session D1): every shop item's approved still (docs/art/wave-2/items/<kind>/
 * <name>.png, 2x, as it looks under Reduce Motion) scaled to at most PREVIEW_W pixels wide and encoded as WebP into
 * public/shop/<id>.webp, plus src/lib/shop/shopPreviews.data.ts (each id's content hash, put on its URL).
 *
 *   bun scripts/shop-previews.ts            write them
 *   bun scripts/shop-previews.ts --check    fail unless the data file matches the images on disk and every shop item has one
 *
 * Re-run it after an item's approved art changes. The same bytes every run (no timestamps).
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { createCanvas, loadImage } from "@napi-rs/canvas";

const PREVIEW_W = 360;
const QUALITY = 82;
const OUT_DIR = "public/shop";
const DATA = "src/lib/shop/shopPreviews.data.ts";

interface JsonItem {
  id: string;
  source: string;
  png: string;
}
const items = (JSON.parse(readFileSync("docs/art/wave-2/catalogue.json", "utf8")) as { items: JsonItem[] }).items.filter(
  (i) => i.source === "shop",
);

function dataFile(): string {
  const lines = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".webp"))
    .sort()
    .map((f) => {
      const hash = createHash("sha256").update(readFileSync(join(OUT_DIR, f))).digest("hex").slice(0, 10);
      return `  ${JSON.stringify(f.replace(/\.webp$/, ""))}: "${hash}",`;
    });
  return `/**
 * Generated by \`bun scripts/shop-previews.ts\`; do not edit. Each shop item's picture (public/shop/<id>.webp, from
 * its approved still in docs/art/wave-2/items) and the picture's content hash, put on its URL.
 */
export const SHOP_PREVIEWS: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`;
}

if (process.argv.includes("--check")) {
  const missing = items.filter((i) => !existsSync(join(OUT_DIR, `${i.id}.webp`))).map((i) => i.id);
  const stale = !existsSync(DATA) || readFileSync(DATA, "utf8") !== dataFile();
  if (missing.length || stale) {
    console.log(`shop-previews: FAIL${missing.length ? ` missing ${missing.join(", ")}` : ""}${stale ? " (data file out of date)" : ""}`);
    process.exit(1);
  }
  console.log(`shop-previews: ${items.length} pictures, data file current`);
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
let total = 0;
for (const item of items) {
  const img = await loadImage(readFileSync(join("docs/art/wave-2", item.png)));
  const scale = Math.min(1, PREVIEW_W / img.width);
  const w = Math.round(img.width * scale);
  const h = Math.round(img.height * scale);
  const canvas = createCanvas(w, h);
  const ctx = canvas.getContext("2d");
  ctx.imageSmoothingQuality = "high";
  ctx.drawImage(img, 0, 0, w, h);
  const webp = await canvas.encode("webp", QUALITY);
  writeFileSync(join(OUT_DIR, `${item.id}.webp`), webp);
  total += webp.length;
}
writeFileSync(DATA, dataFile());
console.log(`shop-previews: ${items.length} pictures, ${Math.round(total / 1024)} KB`);
