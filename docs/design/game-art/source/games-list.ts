import { PUZZLE_CATALOGUE, RETIRED_TYPES } from "../../../../src/lib/duel/catalogue";
import { arcadeGroupOf } from "../../../../src/lib/duel/arcadeGroups";
const rows = Object.entries(PUZZLE_CATALOGUE)
  .filter(([k]) => !RETIRED_TYPES.has(k as never))
  .map(([id, v]) => ({ id, name: v.name, cat: v.category === "arcade" ? "arcade" : v.category, group: v.category === "arcade" ? arcadeGroupOf(id) : undefined }));
