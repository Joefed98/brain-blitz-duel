"""Speed overhaul art: turns the renders from speed_art.py into the app's WebPs and their data file.

    python3 -I export.py <png_dir> [repo_root]

Writes public/speed-art/<name>.webp (lossy 86, alpha kept) and src/lib/fx/speedArt.data.ts: each sprite's URL (its
content hash on the URL, so a redraw reaches every phone), its size in px and, for the round sprites, the radius
inside which every visible pixel sits (as a fraction of half the sprite's width), which speed-overhaul-check holds to
the games' collision bounds. The same PNGs give the same bytes.
"""
import hashlib
import io
import json
import math
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "..", ".."))
SRC = sys.argv[1]
OUT = os.path.join(ROOT, "public", "speed-art")
DATA = os.path.join(ROOT, "src", "lib", "fx", "speedArt.data.ts")

# Display size (CSS / world px) each sprite is drawn at, for the data file; the render is 2-6x that.
OPAQUE = {"flash-wait", "flash-gold", "ascend-board", "chain-board", "bonk-lawn", "tenfall-board", "pull-sky"}
# Downscale factor before encoding (backgrounds are drawn large; small sprites keep their render size).
SHRINK = {"pull-sky": 1.0}


def reach(img):
    """The farthest visible pixel (alpha > 8) from the centre, as a fraction of half the width (circle sprites)."""
    a = img.getchannel("A")
    w, h = a.size
    cx, cy = (w - 1) / 2, (h - 1) / 2
    px = a.load()
    best = 0.0
    for y in range(h):
        for x in range(w):
            if px[x, y] > 8:
                d = math.hypot(x - cx, (y - cy) * w / h)
                best = max(best, d)
    return round(best / (w / 2), 4)


def main():
    os.makedirs(OUT, exist_ok=True)
    entries = {}
    for name in sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".png")):
        img = Image.open(os.path.join(SRC, name + ".png"))
        img = img.convert("RGB") if name in OPAQUE else img.convert("RGBA")
        buf = io.BytesIO()
        img.save(buf, "WEBP", quality=86, method=6, exact=False)
        data = buf.getvalue()
        with open(os.path.join(OUT, name + ".webp"), "wb") as f:
            f.write(data)
        entry = {"url": f"/speed-art/{name}.webp?v={hashlib.sha256(data).hexdigest()[:10]}", "w": img.size[0], "h": img.size[1], "bytes": len(data)}
        if name not in OPAQUE and name.startswith(("bonk-gopher", "bonk-hedgehog", "ascend-disc", "chain-")):
            entry["reach"] = reach(img)
        entries[name] = entry
    lines = [
        "// Generated by docs/design/speed-art/blender/export.py (python3 -I export.py <png_dir>): do not edit.",
        "// The Speed overhaul's Blender sprites (docs/design/speed-art/README.md): URL with its content hash, size in",
        "// px and, for round sprites, the farthest visible pixel as a fraction of half the width (`reach`).",
        "export const SPEED_ART = {",
    ]
    for name, e in entries.items():
        lines.append(f"  {json.dumps(name)}: {json.dumps(e, separators=(', ', ': '))},")
    lines.append("} as const;")
    lines.append("export type SpeedArtName = keyof typeof SPEED_ART;")
    with open(DATA, "w") as f:
        f.write("\n".join(lines) + "\n")
    total = sum(e["bytes"] for e in entries.values())
    print(f"wrote {len(entries)} sprites, {total / 1024:.0f} KB")


if __name__ == "__main__":
    main()
