/**
 * Builds a server-only bank of proved swingRev 3 Grappler courses in
 * src/lib/duel/swingBank.server.ts, the same way Bomb Defusal uses
 * scripts/bomb-bank.ts.
 *
 * Each course is just a seed (the whole cavern, anchors, spikes and dragons
 * are deterministically rebuilt from it) plus the tick its reference beam
 * search completed on, recorded here as the proof result. Proving ~500
 * courses takes a while, so it runs here, not while a room starts.
 *
 *   bun scripts/swing-bank.ts 500
 */
import { writeFileSync } from "node:fs";
import { arcadeSeed } from "../src/lib/duel/arcade.server";
import { proveSwingSeed } from "../src/lib/duel/swingProof.server";
import { swingGameFor, SWING_REV } from "../src/lib/arcade/swing";
import type { SwingBankEntry } from "../src/lib/duel/swingBank.server";

const OUT = "src/lib/duel/swingBank.server.ts";
const target = Number(process.argv[2] ?? 500);

const out: SwingBankEntry[] = [];
const seen = new Set<number>();
const started = Date.now();
let attempts = 0;
const game = swingGameFor(SWING_REV);
while (out.length < target && attempts < target * 20) {
  attempts++;
  const seed = arcadeSeed();
  if (seen.has(seed)) continue;
  seen.add(seed);
  const witness = proveSwingSeed(seed);
  if (!witness) continue;
  let s = game.init(seed);
  const events = new Map(witness.map((e) => [e.t, e]));
  while (!s.ended) s = game.step(s, events.get(s.tick + 1) ?? null);
  out.push({ seed, ticks: s.tick });
}
const seconds = (Date.now() - started) / 1000;
console.log(`built ${out.length}/${target} proved courses in ${seconds.toFixed(1)} s (${attempts} seeds tried)`);

writeFileSync(
  OUT,
  `/* Generated by scripts/swing-bank.ts — do not edit by hand. */\nexport interface SwingBankEntry {\n  seed: number;\n  /** Proof-witness completion tick, recorded at build time (not replayed from). */\n  ticks: number;\n}\n\nexport const SWING_V3_BANK: SwingBankEntry[] = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${out.length} courses to ${OUT}`);
